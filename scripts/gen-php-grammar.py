#!/usr/bin/env python3
"""Generate crates/pun-format/src/php_grammar.rs: PHP's LALR(1) parser tables (bison output for
php-src's Zend/zend_language_parser.y), so `pun_format::lint` accepts exactly what
`token_get_all($code, TOKEN_PARSE)` accepts.

usage: BISON=/path/to/bison scripts/gen-php-grammar.py [php-src tag, default php-8.5.11]
Needs GNU bison >= 3.0 and network access (fetches the grammar from github.com/php/php-src).
"""
import os, re, subprocess, sys, tempfile, urllib.request

TAG = sys.argv[1] if len(sys.argv) > 1 else 'php-8.5.11'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'crates/pun-format/src/php_grammar.rs')
BISON = os.environ.get('BISON', 'bison')

tmp = tempfile.mkdtemp()
y = os.path.join(tmp, 'zend_language_parser.y')
url = f'https://raw.githubusercontent.com/php/php-src/{TAG}/Zend/zend_language_parser.y'
open(y, 'wb').write(urllib.request.urlopen(url).read())
subprocess.run([BISON, '-Wno-other', '-o', os.path.join(tmp, 'parser.c'), y], check=True)
c = open(os.path.join(tmp, 'parser.c')).read()


def define(name):
    return int(re.search(rf'#define {name}\s+\(?(-?\d+)\)?', c).group(1))


def table(name):
    body = re.search(rf'static const \w+ {name}\[\] =\s*\{{(.*?)\}};', c, re.S).group(1)
    return [int(x) for x in re.findall(r'-?\d+', body)]


def tname():
    body = re.search(r'static const char \*const yytname\[\] =\s*\{(.*?)\};', c, re.S).group(1)
    # C literals; adjacent ones ("?""?", which avoids a trigraph) are one string.
    names, prev_end = [], None
    for m in re.finditer(r'"((?:[^"\\]|\\.)*)"|YY_NULLPTR', body):
        text = m.group(1)
        if text is None:
            break
        if prev_end is not None and body[prev_end:m.start()].strip() == '':
            names[-1] += text
        else:
            names.append(text)
        prev_end = m.end()
    return [n.encode().decode('unicode_escape') for n in names]


# Rule numbers (as the tables use them) by their text in the generated actions ("case 199: /* class_modifiers: ... */").
rules = {m.group(2).strip(): int(m.group(1)) for m in re.finditer(r'case (\d+): /\* (.*?) \*/', c)}


def rule(text):
    return rules[text]


declare = re.search(r"statement: \"'declare'\" '\(' const_list '\)' (\$@\d+) declare_statement", '\n'.join(rules)).group(1)

# Kind's PHP variants in declaration order (crates/pun-tokens/src/kind.rs), mapped to bison's internal symbols;
# 2 ("invalid token") for kinds the grammar never names.
kinds_rs = open(os.path.join(ROOT, 'crates/pun-tokens/src/kind.rs')).read()
kind_order = re.findall(r'^\s+(T_\w+),$', kinds_rs.split('php: [')[-1].split(']')[0], re.M)
tokens = dict(re.findall(r'^\s+(T_\w+) = (\d+),', c, re.M))
tokens['T_DOUBLE_COLON'] = tokens['T_PAAMAYIM_NEKUDOTAYIM']
yytranslate = table('yytranslate')
kind_symbol = [yytranslate[int(tokens[k])] if k in tokens else 2 for k in kind_order]


def arr(name, ty, vals):
    rows = [', '.join(map(str, vals[i:i + 20])) for i in range(0, len(vals), 20)]
    return f'pub(crate) static {name}: [{ty}; {len(vals)}] = [\n    ' + ',\n    '.join(rows) + ',\n];\n'


names = tname()
assert len(names) == define('YYNTOKENS') + define('YYNNTS'), len(names)


def rust_str(v):
    return '"' + v.replace('\\', '\\\\').replace('"', '\\"') + '"'


HALT = '"\'__halt_compiler\'"'
AS = '"\'as\'"'
out = [f'''//! Generated by scripts/gen-php-grammar.py from php-src {TAG} Zend/zend_language_parser.y (GNU bison
//! LALR(1) tables). Do not edit.
#![allow(clippy::all, reason = "generated tables")]

use pun_tokens::Kind;

pub(crate) const YYFINAL: i32 = {define('YYFINAL')};
pub(crate) const YYLAST: i32 = {define('YYLAST')};
pub(crate) const YYNTOKENS: i32 = {define('YYNTOKENS')};
pub(crate) const YYPACT_NINF: i32 = {define('YYPACT_NINF')};
pub(crate) const YYTABLE_NINF: i32 = {define('YYTABLE_NINF')};
/// Internal symbol of a single-character token (`';'`, `'('`, ...).
pub(crate) fn char_symbol(c: u8) -> i32 {{
    YYTRANSLATE[c as usize] as i32
}}
/// Internal symbol of a PHP token kind ("invalid token" for kinds the grammar never names).
pub(crate) fn kind_symbol(k: Kind) -> i32 {{
    KIND_SYMBOL.get(k as usize).map_or(2, |&s| s as i32)
}}
pub(crate) const RULE_HALT_INNER: usize = {rule(f"inner_statement: {HALT} '(' ')' ';'")};
pub(crate) const RULE_HALT_TOP: usize = {rule(f"top_statement: {HALT} '(' ')' ';'")};
pub(crate) const RULE_DECLARE: usize = {rule(declare + ': %empty')};
pub(crate) const RULE_CLASS_MODIFIERS: usize = {rule('class_modifiers: class_modifiers class_modifier')};
pub(crate) const RULE_ANON_MODIFIER_FIRST: usize = {rule('anonymous_class_modifiers: class_modifier')};
pub(crate) const RULE_ANON_MODIFIERS: usize = {rule('anonymous_class_modifiers: anonymous_class_modifiers class_modifier')};
pub(crate) const RULE_CPP_MODIFIERS: usize = {rule('optional_cpp_modifiers: non_empty_member_modifiers')};
pub(crate) const RULE_PROPERTY_MODIFIERS: usize = {rule('property_modifiers: non_empty_member_modifiers')};
pub(crate) const RULE_METHOD_MODIFIERS: usize = {rule('method_modifiers: non_empty_member_modifiers')};
pub(crate) const RULE_CONST_MODIFIERS: usize = {rule('class_const_modifiers: non_empty_member_modifiers')};
pub(crate) const RULE_HOOK_MODIFIERS: usize = {rule('property_hook_modifiers: non_empty_member_modifiers')};
pub(crate) const RULE_ALIAS_MODIFIER_NAME: usize = {rule(f"trait_alias: trait_method_reference {AS} member_modifier identifier")};
pub(crate) const RULE_ALIAS_MODIFIER: usize = {rule(f"trait_alias: trait_method_reference {AS} member_modifier")};
''']
out.append(arr('YYTRANSLATE', 'u8', yytranslate))
out.append(arr('KIND_SYMBOL', 'u8', kind_symbol))
for n in ['yypact', 'yydefact', 'yypgoto', 'yydefgoto', 'yytable', 'yycheck', 'yyr1', 'yyr2']:
    out.append(arr(n.upper(), 'i16', table(n)))
out.append(f'pub(crate) static YYTNAME: [&str; {len(names)}] = [\n' + ''.join(f'    {rust_str(n)},\n' for n in names) + '];\n')
open(OUT, 'w').write('\n'.join(out))
print(f'wrote {OUT}: {len(rules)} rule actions, {sum(k != 2 for k in kind_symbol)} token kinds')
