def prose(text: str) -> str:
    """Mapping prose is text with inline code, not executable MDX."""
    return "".join(part if part.startswith("`") else part.replace("&", "&amp;").replace("<", "&lt;")
                   .replace("{", "&#123;").replace("}", "&#125;").replace("|", "&#124;")
                   for part in re.split(r"(`+[^`]*`+)", text))


def code(text: str, language: str = "php") -> str:
    fence = "`" * max(3, max((len(m[0]) + 1 for m in re.finditer(r"`+", text)), default=0))
    return f"{fence}{language}\n{text.rstrip()}\n{fence}\n"


def rule_link(rid: str) -> str:
    return f"[`{rid}`](/docs/rules/{rid})"


def table_code(value: str) -> str:
    return "`" + value.replace("|", "\\|") + "`"


def upstream_rows(data: dict) -> list[dict]:
    rows = [dict(tool=tool, name=name, **entry)
            for tool, entries in data["upstream"].items() if tool not in FAMILY
            for name, entry in entries.items()]
    # Exact identifiers win across sections, then the first matching pattern, as identifiers::entry does.
    candidates = {name for tool in FAMILY for name in data["upstream"].get(tool, {}) if "%s" not in name}
    for filename in ("phpstan-core", "phpstan-extensions"):
        candidates.update(identifier for rule in json.loads((INVENTORY / f"{filename}.json").read_text())
                          for identifier in rule["identifiers"] if re.fullmatch(r"[A-Za-z0-9_]+(?:\.[A-Za-z0-9_]+)+", identifier))
    patterns = [(tool, name, entry, re.compile(re.escape(name).replace("%s", "[A-Za-z0-9_]+")))
                for tool in FAMILY for name, entry in sorted(data["upstream"].get(tool, {}).items()) if "%s" in name]
    for name in sorted(candidates):
        exact = next(((tool, entries[name]) for tool in FAMILY
                      if name in (entries := data["upstream"].get(tool, {}))), None)
        if exact:
            tool, entry = exact
            rows.append(dict(tool=tool, name=name, **entry))
        else:
            match = next(((tool, pattern, entry) for tool, pattern, entry, regex in patterns if regex.fullmatch(name)), None)
            if match:
                tool, pattern, entry = match
                rows.append(dict(tool=tool, name=name, expanded_from=pattern, **entry))
    return rows


def source_urls() -> dict[tuple[str, str], str]:
    urls = {}
    for path in sorted(INVENTORY.glob("*.json")):
        for row in json.loads(path.read_text()):
            if row.get("docs_url"):
                urls[("class", row["fqcn"].replace("\\\\", "\\"))] = row["docs_url"]
    fixers = json.loads((ROOT / "crates/pun-cli/src/gitlab_fixers.json").read_text())
    # Pint wraps these in its Blade-skipping decorator, so its GitLab report names the decorator's path.
    real = {"declare_strict_types": "strict", "fully_qualified_strict_types": "import",
            "global_namespace_import": "import", "no_unused_imports": "import"}
    for name, (_, path) in fixers.items():
        path = f"{real[name]}/{name}" if name in real else path
        urls[("php-cs-fixer", name)] = f"https://cs.symfony.com/doc/rules/{path}.html"
    return urls


def upstream_url(row: dict, urls: dict) -> str:
    tool, name = row["tool"], row["name"]
    if (tool, name) in urls:
        return urls[(tool, name)]
    if tool in ("phpstan", "phpstan-strict-rules", "phpstan-deprecation-rules"):
        return f"https://phpstan.org/error-identifiers/{quote(name)}"
    if tool == "phpstan-classes":
        return urls.get(("class", row["class"].replace("\\\\", "\\")), "https://phpstan.org/user-guide/rule-levels")
    if "class" in row:
        return urls.get(("class", row["class"].replace("\\\\", "\\")), "https://getrector.com/find-rule")
    if tool == "phpstan-parameters":
        return "https://phpstan.org/config-reference"
    if tool == "mago-linter":
        return f"https://mago.carthage.software/1.57.0/en/tools/linter/rules/#{quote(name)}"
    if tool == "pun":
        return "https://mago.carthage.software/1.57.0/en/tools/linter/rules/"
    if tool == "mago-analyzer":
        return "https://mago.carthage.software/1.57.0/en/tools/analyzer/overview/"
    if tool == "larastan":
        return "https://github.com/larastan/larastan/blob/v3.14.0/docs/rules.md"
    return "https://laravel.com/docs/pint"


def upstream_link(row: dict, urls: dict) -> str:
    return f"[`{row['name']}`]({upstream_url(row, urls)})"


def memberships(data: dict, command: str, rule: dict) -> list[str]:
    if command == "format":
        return [f"format-{p}" for p in rule.get("presets", [])]
    if command == "lint":
        return rule.get("sets", [])
    presets = data["meta"]["presets"]["analyse"]
    return [f"analyse-{p}" for p in presets[presets.index(rule["preset"]):]] if "preset" in rule else []


def badges(data: dict, rid: str, rule: dict, sources: list[dict], links: bool = True) -> str:
    command, group, _ = rid.split("/")
    enabled = memberships(data, command, rule)
    folder = "sets" if command == "lint" else "presets"
    labels = [f"[`{name}`](/docs/rules/{folder}/{name})" if links else f"`{name}`" for name in enabled]
    kind = "set" if command == "lint" else "preset"
    joined = " and ".join(labels) if len(labels) < 3 else ", ".join(labels[:-1]) + ", and " + labels[-1]
    sentences = [f"In the {joined} {kind}{'s' if len(labels) > 1 else ''}." if labels else f"Not in any {kind}."]
    if command == "analyse" and len(labels) > 1:
        # Analyse presets are cumulative, so the lowest one names them all.
        sentences = [f"In the {labels[0]} preset and every stricter one."]
    sentences.append({"safe": "Safe fix.", "unsafe": "Unsafe fix: it can change behaviour.",
                      "mixed": "Safe fix where types prove it, unsafe otherwise.", "none": "Report only."}[rule.get("fix", "none")])
    if rule.get("intent"):
        sentences.append(f"Intent: {rule['intent']}.")
    ecosystem = next((e for e in data["meta"]["ecosystems"] if group == e or group.startswith(e + "-")), None)
    if ecosystem:
        sentences.append(f"Runs when {ecosystem} is installed.")
    if rule.get("gated_by") or re.match(r"(php|laravel|phpunit|pest)-\d", group):
        gate = group if re.search(r"\d", group) else rule["gated_by"]
        sentences.append(f"Gated by {gate}.")
    gates = sorted({s["gated_by"] for s in sources if s.get("gated_by")})
    if gates:
        sentences.append("Upstream gates: " + ", ".join(f"`{gate}`" for gate in gates) + ".")
    if not sources:
        sentences.append("No upstream equivalent.")
    if not rule.get("ported"):
        sentences.append("**Planned: not in Pun yet.** Enabling it is a config error.")
    return " ".join(sentences)


def pun_value(value: object, option: dict) -> object:
    values = {up: pun for pun, up in option.get("values", {}).items()}
    if value is None:
        return option.get("null")
    if isinstance(value, str):
        return values.get(value, value)
    if isinstance(value, list):
        if option["type"] in ("map", "int-or-map") and not value:
            return {}
        return [pun_value(v, option) for v in value]
    if isinstance(value, dict):
        keys = {up: pun for pun, up in option.get("keys", {}).items()}
        return {keys.get(k, k): pun_value(v, option) for k, v in value.items()}
    return value


def toml_value(value: object) -> str:
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{json.dumps(k)} = {toml_value(v)}" for k, v in value.items()) + " }"
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    return json.dumps(value, ensure_ascii=False)


def rule_page(data: dict, rid: str, rule: dict, sources: list[dict], urls: dict, defaults: dict) -> str:
    command, group, name = rid.split("/")
    body = f'<RuleId id="{rid}" />\n\n' + badges(data, rid, rule, sources)
    if rule.get("summary"):
        body += "\n\n## What it does\n\n" + prose(rule["summary"])
    if rule.get("why"):
        body += "\n\n### Why\n\n" + prose(rule["why"])
    if rule.get("examples"):
        body += "\n\n## Examples\n\n"
    for example in rule.get("examples", []):
        if example.get("title"):
            body += "### " + prose(example["title"]) + "\n\n"
        if "before" in example:
            body += "Avoid:\n\n" + code(example["before"]) + "\nPrefer:\n\n" + code(example["after"])
        else:
            body += code(example["code"]) + "\nPun reports:\n\n" + code(example["message"], "text")
    if rule.get("ported"):
        value = {"format": "true", "lint": '"error"', "analyse": '"on"'}[command]
        body += "\n\n## Configuration\n\n" + code(f'[{command}.rules]\n"{group}/{name}" = {value}', "toml title=\"pun.toml\"")
        file_only = command == "format" or any(s["tool"] in ("php-cs-fixer", "pint") for s in sources)
        override = "an [override](/docs/configuration/pun-toml#lint)" if command == "lint" else ""
        if not rule.get("ignorable", True):
            skip = f" To skip it in some files, add {override}." if override else ""
            body += f"\nIgnore comments and baselines cannot suppress it.{skip}"
        elif file_only:
            comment = "a [`@pun-ignore-file`](/docs/configuration/ignore-comments) comment"
            body += f"\nTo skip it in some files, add {override + ' or ' if override else ''}{comment}."
        else:
            comment = "an [ignore comment](/docs/configuration/ignore-comments)"
            body += f"\nTo skip it in some files or lines, add {override + ' or ' if override else ''}{comment}."
    options = data.get("options", {}).get(rid, {})
    if options:
        body += "\n\n## Options\n\n| Name | Type | Allowed values | Default | Upstream name |\n| --- | --- | --- | --- | --- |\n"
        fixer = next((s["name"] for s in sources if s["tool"] in ("php-cs-fixer", "pint")), "")
        for key, option in options.items():
            own = option.get("origin") == "pun"
            default = next((o for o in defaults.get(fixer, []) if o["name"] == option["upstream"]), None)
            default = {"default": option["default"]} if own else default
            value = pun_value(default["default"], option) if default else None
            shown = table_code(toml_value(value)) if value is not None else "Not set" if default else "Unknown"
            allowed = ", ".join(table_code(v) for v in option.get("values", {})) or "Any"
            upstream = "None (Pun's own)" if own else f"`{option['upstream']}`"
            body += f"| `{key}` | `{option['type']}` | {allowed} | {shown} | {upstream} |\n"
    if sources:
        body = body.rstrip() + "\n\n## Replaces\n\n"
        body += "\n".join(f"- {upstream_link(s, urls)} ({s['tool']}{', risky' if s.get('risky') else ''})" for s in sources)
    if rule.get("replaces"):
        body += ("\n\n## Merged rules\n\nThese old IDs are now this rule. A config that still names one stops with an error. "
                 "See [merged rules](/docs/migrate/merged-rules).\n\n")
        body += "\n".join(f"- `{old}`" for old in rule["replaces"])
        if rule.get("note"):
            body += "\n\n" + prose(rule["note"])
    fixed = rule.get("fixed_by", [])
    fixes = [f"{cmd}/{key}" for cmd, rules in data["rules"].items() for key, r in rules.items() if rid in r.get("fixed_by", [])]
    conflicts = [b if a == rid else a for a, b in data["meta"]["conflicts"] if rid in (a, b)]
    if fixed or fixes or conflicts:
        body += "\n\n## Linked rules\n\n" + "\n".join(
            [f"- Fixed by {rule_link(r)}." for r in fixed] + [f"- Fixes reports from {rule_link(r)}." for r in fixes]
            + [f"- Conflicts with {rule_link(r)}. You cannot enable both." for r in conflicts])
    body += f"\n\n[More {command}/{group} rules](/docs/rules/{command}/{group}) · [Edit this page]({EDIT})"
    return page(rid, body)


def page(title: str, body: str) -> str:
    return f'---\ntitle: {json.dumps(title)}\npagination: false\n---\n\n{{/* {MARKER} */}}\n\n{body.rstrip()}\n'


def meta(title: str, pages: list[str]) -> str:
    return (f'// {MARKER}\nimport {{ defineMeta }} from "blume";\n\n'
            f'export default defineMeta({{ title: {json.dumps(title)}, display: "group", directory: "none", '
            f'pages: {json.dumps(pages)} }});\n')


def format_config(data: dict, preset: str) -> dict[str, object]:
    """Expand the same pinned set exports as pun_config::rule_set / resolve_subset."""
    sets = json.loads((ROOT / "crates/pun-config/presets/sets.json").read_text())

    def subset(name: str, on: bool) -> dict:
        definition = sets[name]
        result = dict(definition)
        # resolve_subset visits the BTreeMap in key order, not declaration order.
        for key, value in sorted(definition.items()):
            if key.startswith("@"):
                result.pop(key)
                result.update(subset(key, on))
            else:
                result[key] = value if on else False
        return result

    path = ROOT / f"crates/pun-config/presets/{preset}.json"
    raw = json.loads(path.read_text())
    resolved = {}
    for key, value in raw.get("rules_as_configured", raw).items():
        resolved.update(subset(key, value is True) if key in sets else {key: value})
    result = {}
    for tool in ("php-cs-fixer", "pint", "pun"):
        for name, source in data["upstream"].get(tool, {}).items():
            rid = source.get("pun", "")
            if rid.startswith("format/") and name in resolved and resolved[name] is not False:
                value = resolved[name]
                if isinstance(value, dict):
                    schema = data.get("options", {}).get(rid, {})
                    value = {key: pun_value(value[option["upstream"]], option)
                             for key, option in schema.items() if option["upstream"] in value}
                    value = {k: v for k, v in value.items() if v is not None}
                result[rid] = value or True
    return result


def selection_page(data: dict, command: str, name: str, on: dict) -> str:
    is_set = command == "lint"
    title = f"{name} {'set' if is_set else command + ' preset'}"
    purposes = {
        "format": {"laravel": "Laravel Pint's default formatting style.", "psr12": "The PSR-12 formatting standard.",
                   "empty": "No format rules. Every enabled rule is explicit."},
        "lint": {"dead-code": "Code that never runs, or whose result is never used.",
                 "modernize": "Newer PHP syntax, up to your configured PHP target version.",
                 "code-quality": "Simpler equivalents and likely bugs.", "types": "Missing type declarations and PHPDoc types.",
                 "early-return": "Early returns and continues instead of nesting.",
                 "privatization": "Narrower visibility, final classes and constants.",
                 "naming": "Names that match their types. No rules remain in this set after upstream deprecations.",
                 "coding-style": "One consistent way to write the same thing."},
        "analyse": {"basic": "Unknown names, wrong argument counts and undefined variables.",
                    "essential": "Unknown methods and properties, PHPDoc, return and property types.",
                    "recommended": "Dead code, constant conditions and argument types. The default analyse preset.",
                    "strict": "Missing typehints, union types and nullable values.", "max": "Explicit and implicit mixed types."},
    }
    body = purposes[command][name] + "\n\n"
    body += code(f'[{command}]\n' + (f'sets = ["{name}"]' if is_set else f'preset = "{name}"'), "toml")
    body += "\nEcosystem and target-version gates still apply. Planned rules do not run.\n"
    if command == "analyse":
        presets = data["meta"]["presets"]["analyse"]
        bands = [(0, 1), (2, 3), (4, 5), (6, 8), (9, 10)]
        low, high = bands[presets.index(name)]
        body += f"\nCovers PHPStan levels {low}–{high}, and every lower preset with them (levels 0–{high}). "
        body += "Extension rules join by their own preset, not by PHPStan level.\n\n"
        switches = [s for p in presets[:presets.index(name) + 1] for s in data["meta"]["preset_switches"].get(p, [])]
        if switches:
            body += "Type switches it turns on:\n\n" + code("[analyse]\n" + "\n".join(f"{s} = true" for s in switches), "toml")
        body += "\n### What each PHPStan level adds\n"
        for level in range(high + 1):
            added = sorted({r["pun"] for r in data["upstream"]["phpstan-classes"].values()
                            if str(r.get("level")) == str(level) and r.get("pun", "").startswith("analyse/")})
            body += f"\n#### Level {level}\n\n"
            body += "\n".join(f"- {rule_link(r)}" for r in added) or {
                7: "Checks each member of a union (`union-types = true`).",
                8: "Checks nullable values (`nullables = true`).",
                9: "Checks explicit mixed (`explicit-mixed = true`).",
                10: "Checks implicit mixed (`implicit-mixed = true`).",
            }.get(level, "No new rules.")
            body += "\n"
    body += f"\n## Enabled rules ({len(on)})\n\n| Rule | Configuration | Status |\n| --- | --- | --- |\n"
    for rid, config in sorted(on.items()):
        rule = data["rules"][command][rid.split("/", 1)[1]]
        status = "Ported" if rule.get("ported") else "Planned"
        body += f"| {rule_link(rid)} | `{toml_value(config)}` | {status} |\n"
    if not on:
        body += "\nNo rules.\n"
    off = [f"{command}/{key}" for key in sorted(data["rules"][command]) if f"{command}/{key}" not in on]
    body += f"\n## Rules left off ({len(off)})\n\n"
    body += "\n".join(f"- {rule_link(r)}" for r in off) or "None."
    return page(title, body)


