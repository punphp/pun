def migration_pages(data: dict, rows: list[dict], urls: dict) -> dict[Path, str]:
    out, tables = {}, {}
    pun_only = [f"{cmd}/{key}" for cmd, rules in data["rules"].items() for key, rule in rules.items() if rule.get("pun_only")]
    for tool, sections in TOOLS.items():
        selected = [r for r in rows if r["tool"] in sections]
        by_rule = defaultdict(list)
        for row in selected:
            if row.get("pun"):
                by_rule[row["pun"]].append(row["name"])
        tables[tool] = []
        unsupported = defaultdict(list)
        for row in selected:
            rid = row.get("pun", "")
            reason = row.get("unsupported") or row.get("drop")
            note = reason or "Same."
            if rid and len(by_rule[rid]) > 1:
                others = [n for n in by_rule[rid] if n != row["name"]]
                note = "Merged with " + ", ".join(others[:3])
                note += f" and {len(others) - 3} others (see the rule's Replaces section)." if len(others) > 3 else "."
            if row.get("options") and row["options"] != "none":
                note += " Options: " + row["options"] + "."
            if row.get("expanded_from"):
                note += " Expanded from " + row["expanded_from"] + "."
            if rid.startswith(COMMANDS):
                command, key = rid.split("/", 1)
                if not data["rules"][command][key].get("ported"):
                    note += " Planned: not ported yet."
            targets = [r for r in [rid, *row.get("also", [])] if r.startswith(COMMANDS)]
            tables[tool].append(dict(name=row["name"], tool=row["tool"], url=upstream_url(row, urls), rules=targets,
                                     note=note, unsupported=bool(reason)))
            if reason:
                unsupported[reason].append(row)
        body = "## Config translation\n\n" + translation(tool)
        body += f'\n## Rule mapping\n\n<MigrationTable tool="{tool}" />\n\n## Unsupported rules by reason\n\n'
        if not unsupported:
            body += "No dropped or out-of-scope entries in this mapping. Planned rules are marked separately.\n"
        for reason, entries in sorted(unsupported.items()):
            body += "### " + prose(reason) + "\n\n"
            body += ", ".join(upstream_link(r, urls) for r in entries)
            body += ".\n\n"
        body += "\n## Pun-only rules\n\n" + "\n".join(f"- {rule_link(r)}" for r in pun_only)
        out[CONTENT / f"migrate/from/{tool}.mdx"] = page(f"Coming from {tool}", body)
    out[GENERATED / "migrations.json"] = json.dumps({"_generated": MARKER, "tools": tables}, ensure_ascii=False, indent=2) + "\n"
    out[CONTENT / "migrate/meta.ts"] = meta("Migration mappings", ["from"])
    out[CONTENT / "migrate/from/meta.ts"] = meta("Coming from", list(TOOLS))
    body = "Upstream rule names, option translations, and unsupported items. Planned rules have a mapping but are not implemented.\n\n"
    body += "\n".join(f"- [{tool}](/docs/migrate/from/{tool})" for tool in TOOLS)
    body += "\n\n[Run the migration](/docs/commands/migrate)."
    out[CONTENT / "migrate/from/index.mdx"] = page("Coming from another tool", body)
    out[CONTENT / "migrate/index.mdx"] = page("Migration mappings", "[Choose your upstream tool](/docs/migrate/from).")
    return out


def directory(data: dict, sources: dict) -> dict[Path, str]:
    rows = []
    for command in COMMANDS:
        for key, rule in sorted(data["rules"][command].items()):
            rid = f"{command}/{key}"
            group = key.split("/")[0]
            names = {s["name"] for s in sources[rid]}
            names.update(s["expanded_from"] for s in sources[rid] if s.get("expanded_from"))
            names.update(s["class"].split("\\")[-1] for s in sources[rid] if s.get("class"))
            names.update(s["class"] for s in sources[rid] if s.get("class"))
            tools = {tool for tool, sections in TOOLS.items() if any(s["tool"] in sections for s in sources[rid])}
            tools.update(s["tool"] for s in sources[rid] if s["tool"] in ("phpstan-strict-rules", "phpstan-deprecation-rules", "rector-laravel", "rector-phpunit", "pest-plugin-rector"))
            for source in sources[rid]:
                if source["tool"] == "phpstan-classes":
                    tools.update((source["package"], "larastan" if source["package"] == "larastan" else "phpstan"))
                elif source["tool"] == "phpstan-parameters":
                    tools.add("phpstan")
            ecosystem = next((e for e in data["meta"]["ecosystems"] if group == e or group.startswith(e + "-")), "core")
            rows.append(dict(id=rid, command=command, group=group, summary=re.sub(r"`+", "", rule.get("summary", "")),
                             enabled=memberships(data, command, rule), fix=rule.get("fix", "none"), ecosystem=ecosystem,
                             tools=sorted(tools), upstream=sorted(names), ported=bool(rule.get("ported"))))
    counts = ", ".join(f"{len(data['rules'][c])} {c}" for c in COMMANDS)
    body = f"**{len(rows):,} rules: {counts}. {sum(r['fix'] != 'none' for r in rows)} fixable.** "
    body += f"{sum(r['ported'] for r in rows)} ported; the rest are marked Planned.\n\n[Jump to the searchable table](#all-rules).\n\n"
    groups = data["meta"]["groups"]
    for title, names in (
        ("Topic groups", [g for g in groups if g not in data["meta"]["ecosystems"] and not re.search(r"-\d", g)]),
        ("Ecosystem groups", data["meta"]["ecosystems"]),
        ("Upgrade groups", [g for g in groups if re.search(r"-\d", g)]),
    ):
        body += f"## {title}\n\n<CardGroup cols={{3}}>\n"
        for group in names:
            members = [r for r in rows if r["group"] == group]
            body += f'<Card title="{group} · {len(members)} rules">\n\n{prose(groups[group])}.\n\n'
            body += " · ".join(f"[{command}: {sum(r['command'] == command for r in members)}](/docs/rules/{command}/{group})"
                               for command in COMMANDS if any(r["command"] == command for r in members))
            body += "\n\n</Card>\n"
        body += "</CardGroup>\n\n"
    body += "## All rules\n\nSearch a Pun ID or any upstream name. Filters combine and stay in the URL. Planned rules remain in the table.\n\n<RulesDirectory />"
    content = page("Rules", body).replace("pagination: false", "pagination: false\nmode: wide")
    selections = [f"{command}-{preset}" for command, presets in data["meta"]["presets"].items() for preset in presets]
    selections += data["meta"]["sets"]
    return {CONTENT / "rules/index.mdx": content,
            GENERATED / "rules.json": json.dumps({"_generated": MARKER, "selections": selections, "rules": rows}, ensure_ascii=False, indent=2) + "\n"}


def generate(data: dict) -> dict[Path, str]:
    out = {}
    urls = source_urls()
    defaults = json.loads((ROOT / "crates/pun-config/tests/fixer_options.json").read_text())
    sources = defaultdict(list)
    rows = upstream_rows(data)
    for source in rows:
        for rid in [source.get("pun"), *source.get("also", [])]:
            if rid:
                sources[rid].append(source)
    out[CONTENT / "rules/meta.ts"] = meta("Rules", [*COMMANDS, "presets", "sets"])
    for command in COMMANDS:
        groups = {}
        for key, rule in sorted(data["rules"][command].items()):
            group, name = key.split("/")
            groups.setdefault(group, []).append(name)
            rid = f"{command}/{key}"
            out[CONTENT / f"rules/{command}/{key}.mdx"] = rule_page(data, rid, rule, sources[rid], urls, defaults)
        out[CONTENT / f"rules/{command}/meta.ts"] = meta(command, list(groups))
        for group, names in groups.items():
            out[CONTENT / f"rules/{command}/{group}/meta.ts"] = meta(group, names)
            counts = ", ".join(f"{cmd}: {sum(key.startswith(group + '/') for key in rules)}"
                               for cmd, rules in data["rules"].items())
            body = prose(data["meta"]["groups"][group]) + f".\n\nAcross commands: {counts}.\n\n<CardGroup cols={{2}}>\n"
            for name in names:
                rid = f"{command}/{group}/{name}"
                rule = data["rules"][command][f"{group}/{name}"]
                body += f'<Card title="{rid}">\n\n{rule_link(rid)}\n\n'
                body += prose(rule.get("summary", "")) + "\n\n" + badges(data, rid, rule, sources[rid]) + "\n\n</Card>\n"
            out[CONTENT / f"rules/{command}/{group}/index.mdx"] = page(f"{command}/{group}", body + "</CardGroup>")
        links = "\n".join(f"- [{g}](/docs/rules/{command}/{g}) ({len(ns)} rules)" for g, ns in groups.items())
        out[CONTENT / f"rules/{command}/index.mdx"] = page(f"{command} rules", links)
    preset_names = []
    for command in ("format", "analyse"):
        for preset in data["meta"]["presets"][command]:
            slug = f"{command}-{preset}"
            preset_names.append(slug)
            on = format_config(data, preset) if command == "format" else {
                f"analyse/{key}": True for key, rule in data["rules"]["analyse"].items()
                if slug in memberships(data, "analyse", rule)}
            out[CONTENT / f"rules/presets/{slug}.mdx"] = selection_page(data, command, preset, on)
    out[CONTENT / "rules/presets/meta.ts"] = meta("Presets", preset_names)
    out[CONTENT / "rules/presets/index.mdx"] = page("Rule presets", "\n".join(
        f"- [{name}](/docs/rules/presets/{name})" for name in preset_names))
    for name in data["meta"]["sets"]:
        on = {f"lint/{key}": "error" for key, rule in data["rules"]["lint"].items() if name in rule.get("sets", [])}
        out[CONTENT / f"rules/sets/{name}.mdx"] = selection_page(data, "lint", name, on)
    out[CONTENT / "rules/sets/meta.ts"] = meta("Sets", data["meta"]["sets"])
    out[CONTENT / "rules/sets/index.mdx"] = page("Lint sets", "\n".join(
        f"- [{name}](/docs/rules/sets/{name})" for name in data["meta"]["sets"]))
    out.update(migration_pages(data, rows, urls))
    # Search also accepts literal mapping patterns, including those shadowed by an exact identifier.
    for tool in FAMILY:
        for name, entry in data["upstream"][tool].items():
            if "%s" in name and entry.get("pun"):
                sources[entry["pun"]].append(dict(tool=tool, name=name, **entry))
    out.update(directory(data, sources))
    return out


def sync(output: dict[Path, str], check: bool) -> int:
    # Only files carrying our marker belong to the generator. Never remove handwritten content.
    owned = {p for p in CONTENT.rglob("*")
             if p.suffix in (".mdx", ".ts") and MARKER in p.read_text()}
    owned.update(p for p in GENERATED.glob("*.json") if MARKER in p.read_text())
    stale = sorted(owned - output.keys())
    changed = [p for p, text in output.items() if not p.exists() or p.read_text() != text]
    for path in stale + changed:
        display = path.relative_to(ROOT) if path.is_relative_to(ROOT) else path
        print(f"{'obsolete' if path in stale else 'out of date'}: {display}")
    if check:
        return int(bool(stale or changed))
    for path in stale:
        path.unlink()
    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(output[path])
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = tomllib.loads(MAPPING.read_text())
    output = generate(data)
    result = sync(output, args.check)
    print(f"{len(output)} generated files; {'out of date' if result else 'in sync'}")
    return result


