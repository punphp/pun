#!/usr/bin/env python3
"""Generate the public rule reference. Run with --check to reject missing, stale or obsolete output."""
import argparse
import json
import re
import tomllib
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent
MAPPING = ROOT / "crates/pun-config/rules/mapping.toml"
CONTENT = ROOT / "docs/content/docs"
MARKER = "Generated by scripts/gen-rule-docs.py. Edit mapping.toml, not this file."
COMMANDS = ("format", "lint", "analyse")
INVENTORY = MAPPING.parent / "upstream"
SOURCE = "https://github.com/punphp/pun/blob/main/crates/pun-config/rules/mapping.toml"
EDIT = "https://github.com/punphp/pun/edit/main/crates/pun-config/rules/mapping.toml"


def prose(text: str) -> str:
    """Mapping prose is text with inline code, not executable MDX."""
    return "".join(part if part.startswith("`") else part.replace("&", "&amp;").replace("<", "&lt;")
                   .replace("{", "&#123;").replace("}", "&#125;").replace("|", "&#124;")
                   for part in re.split(r"(`+[^`]*`+)", text))


def code(text: str, language: str = "php") -> str:
    fence = "`" * max(3, max((len(m[0]) + 1 for m in re.finditer(r"`+", text)), default=0))
    return f"{fence}{language}\n{text.rstrip()}\n{fence}\n"


def rule_link(rid: str) -> str:
    return f"[`{rid}`](/docs/rules/{rid})"


def upstream_rows(data: dict) -> list[dict]:
    return [dict(tool=tool, name=name, **entry)
            for tool, entries in data["upstream"].items() for name, entry in entries.items()]


def source_urls() -> dict[tuple[str, str], str]:
    urls = {}
    for path in sorted(INVENTORY.glob("*.json")):
        for row in json.loads(path.read_text()):
            if row.get("docs_url"):
                urls[("class", row["fqcn"].replace("\\\\", "\\"))] = row["docs_url"]
    fixers = json.loads((ROOT / "crates/pun-cli/src/gitlab_fixers.json").read_text())
    for name, (_, path) in fixers.items():
        urls[("php-cs-fixer", name)] = f"https://cs.symfony.com/doc/rules/{path}.html"
    return urls


def upstream_url(row: dict, urls: dict) -> str:
    tool, name = row["tool"], row["name"]
    if (tool, name) in urls:
        return urls[(tool, name)]
    if tool in ("phpstan", "phpstan-strict-rules", "phpstan-deprecation-rules"):
        return f"https://phpstan.org/error-identifiers/{quote(name)}"
    if "class" in row:
        return urls[("class", row["class"].replace("\\\\", "\\"))]
    if tool == "mago-linter":
        return f"https://mago.carthage.software/1.57.0/en/tools/linter/rules/#{quote(name)}"
    if tool == "pun":
        return "https://mago.carthage.software/1.57.0/en/tools/linter/rules/"
    if tool == "mago-analyzer":
        return "https://mago.carthage.software/1.57.0/en/tools/analyzer/overview/"
    if tool == "larastan":
        return "https://github.com/larastan/larastan/blob/v3.10.0/docs/rules.md"
    return "https://laravel.com/docs/pint"


def upstream_link(row: dict, urls: dict) -> str:
    return f"[`{row['name']}`]({upstream_url(row, urls)})"


def memberships(data: dict, command: str, rule: dict) -> list[str]:
    if command == "format":
        return [f"format-{p}" for p in rule.get("presets", [])]
    if command == "lint":
        return rule.get("sets", [])
    presets = data["meta"]["presets"]["analyse"]
    return [f"analyse-{p}" for p in presets[presets.index(rule["preset"]):]] if "preset" in rule else []


def badges(data: dict, rid: str, rule: dict) -> str:
    command, group, _ = rid.split("/")
    enabled = memberships(data, command, rule)
    folder = "sets" if command == "lint" else "presets"
    labels = [f"[`{name}`](/docs/rules/{folder}/{name})" for name in enabled]
    sentences = [f"Enabled by the {', '.join(labels)} {'sets' if command == 'lint' else 'presets'}."
                 if labels else "Not in any preset or set. Enable it by name or group."]
    fix = rule.get("fix", "none")
    sentences.append("Fix: " + {"safe": "safe (keeps behaviour).", "unsafe": "unsafe (can change behaviour).",
                                "mixed": "mixed (safe where types prove it, unsafe otherwise).", "none": "none (report only)."}[fix])
    intent = rule.get("intent", {"format": "layout", "lint": "a better way to write it", "analyse": "type correctness"}[command])
    sentences.append(f"Intent: {intent}.")
    ecosystem = next((e for e in data["meta"]["ecosystems"] if group == e or group.startswith(e + "-")), None)
    if ecosystem:
        sentences.append(f"Runs when {ecosystem} is installed.")
    if rule.get("gated_by") or re.match(r"(php|laravel|phpunit|pest)-\d", group):
        sentences.append(f"Gated by {group if re.search(r'\d', group) else rule['gated_by']}.")
    if not rule.get("ported"):
        sentences.append("**Planned: not in Pun yet.** Enabling it in pun.toml is a config error.")
    return " ".join(sentences)


def pun_value(value: object, option: dict) -> object:
    values = {up: pun for pun, up in option.get("values", {}).items()}
    if value is None:
        return option.get("null")
    if isinstance(value, str):
        return values.get(value, value)
    if isinstance(value, list):
        if option["type"] in ("map", "int-or-map") and not value:
            return {}
        return [pun_value(v, option) for v in value]
    if isinstance(value, dict):
        keys = {up: pun for pun, up in option.get("keys", {}).items()}
        return {keys.get(k, k): pun_value(v, option) for k, v in value.items()}
    return value


def toml_value(value: object) -> str:
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{json.dumps(k)} = {toml_value(v)}" for k, v in value.items()) + " }"
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    return json.dumps(value, ensure_ascii=False)


def rule_page(data: dict, rid: str, rule: dict, sources: list[dict], urls: dict, defaults: dict) -> str:
    command, group, name = rid.split("/")
    body = f'<RuleId id="{rid}" />\n\n' + badges(data, rid, rule)
    body += "\n\n## Replaces\n\n"
    body += "\n".join(f"- {upstream_link(s, urls)} ({s['tool']}{', risky' if s.get('risky') else ''})."
                      for s in sources) or "Pun-only rule. No upstream equivalent."
    body += "\n\n## Turn it on\n\n" + code(f'[{command}.rules]\n"{group}/{name}" = ' + ('"error"' if command == "lint" else "true"), "toml title=\"pun.toml\"")
    ignore = "@pun-ignore-file" if command == "format" else "@pun-ignore"
    body += "\n" + code(f"// {ignore} {rid} -- explain the exception")
    body += "\n## What it does\n\n" + prose(rule.get("summary", "Summary not written yet."))
    if rule.get("why"):
        body += "\n\n### Why\n\n" + prose(rule["why"])
    body += "\n\n## Examples\n\n"
    if not rule.get("examples"):
        body += "Examples not written yet."
    for example in rule.get("examples", []):
        if example.get("title"):
            body += "### " + prose(example["title"]) + "\n\n"
        if "before" in example:
            body += "Avoid:\n\n" + code(example["before"]) + "\nPrefer:\n\n" + code(example["after"])
        else:
            body += code(example["code"]) + "\nPun reports:\n\n" + code(example["message"], "text")
    body += "\n\n## Options\n\n"
    options = data.get("options", {}).get(rid, {})
    if not options:
        body += "No configurable options."
    else:
        body += "| Name | Type | Allowed values | Default | Upstream name |\n| --- | --- | --- | --- | --- |\n"
        fixer = next((s["name"] for s in sources if s["tool"] in ("php-cs-fixer", "pint")), "")
        for key, option in options.items():
            default = next((o for o in defaults.get(fixer, []) if o["name"] == option["upstream"]), None)
            value = pun_value(default["default"], option) if default else None
            shown = f"`{prose(toml_value(value))}`" if value is not None else "omit (upstream null)" if default else "not recorded"
            allowed = ", ".join(f"`{prose(v)}`" for v in option.get("values", {})) or "Any value of this type"
            body += f"| `{key}` | `{option['type']}` | {allowed} | {shown} | `{option['upstream']}` |\n"
    fixed = rule.get("fixed_by", [])
    fixes = [f"{cmd}/{key}" for cmd, rules in data["rules"].items() for key, r in rules.items() if rid in r.get("fixed_by", [])]
    conflicts = [b if a == rid else a for a, b in data["meta"]["conflicts"] if rid in (a, b)]
    body += "\n\n## Linked rules\n\n"
    body += "\n".join(f"- Fixed by {rule_link(r)}." for r in fixed)
    body += "\n".join(f"\n- Fixes reports from {rule_link(r)}." for r in fixes)
    body += "\n".join(f"\n- Conflicts with {rule_link(r)}. A config cannot enable both." for r in conflicts)
    if not (fixed or fixes or conflicts):
        body += "No linked rules or conflicts."
    siblings = [f"{command}/{key}" for key in sorted(data["rules"][command]) if key.startswith(group + "/") and key != f"{group}/{name}"]
    body += f"\n\n## Other rules in {command}/{group}\n\n"
    body += "\n".join(f"- {rule_link(r)}" for r in siblings) or "This is the only rule in this group."
    body += f"\n\n[Group reference](/docs/rules/{command}/{group}) · [Source mapping]({SOURCE}) · [Edit this page]({EDIT})"
    return page(rid, body)


def page(title: str, body: str) -> str:
    return f'---\ntitle: {json.dumps(title)}\npagination: false\n---\n\n{{/* {MARKER} */}}\n\n{body.rstrip()}\n'


def meta(title: str, pages: list[str]) -> str:
    return (f'// {MARKER}\nimport {{ defineMeta }} from "blume";\n\n'
            f'export default defineMeta({{ title: {json.dumps(title)}, directory: "none", '
            f'pages: {json.dumps(pages)} }});\n')


def format_config(data: dict, preset: str) -> dict[str, object]:
    """Expand the same pinned set exports as pun_config::rule_set / resolve_subset."""
    sets = json.loads((ROOT / "crates/pun-config/presets/sets.json").read_text())

    def subset(name: str, on: bool) -> dict:
        definition = sets[name]
        result = dict(definition)
        # resolve_subset visits the BTreeMap in key order, not declaration order.
        for key, value in sorted(definition.items()):
            if key.startswith("@"):
                result.pop(key)
                result.update(subset(key, on))
            else:
                result[key] = value if on else False
        return result

    path = ROOT / ("docs/presets/laravel.json" if preset == "laravel" else f"crates/pun-config/presets/{preset}.json")
    raw = json.loads(path.read_text())
    resolved = {}
    for key, value in raw.get("rules_as_configured", raw).items():
        resolved.update(subset(key, value is True) if key in sets else {key: value})
    result = {}
    for tool in ("php-cs-fixer", "pint", "pun"):
        for name, source in data["upstream"].get(tool, {}).items():
            rid = source.get("pun", "")
            if rid.startswith("format/") and name in resolved and resolved[name] is not False:
                value = resolved[name]
                if isinstance(value, dict):
                    schema = data.get("options", {}).get(rid, {})
                    value = {key: pun_value(value[option["upstream"]], option)
                             for key, option in schema.items() if option["upstream"] in value}
                    value = {k: v for k, v in value.items() if v is not None}
                result[rid] = value or True
    return result


def selection_page(data: dict, command: str, name: str, on: dict) -> str:
    is_set = command == "lint"
    title = f"{name} {'set' if is_set else command + ' preset'}"
    body = code(f'[{command}]\n' + (f'sets = ["{name}"]' if is_set else f'preset = "{name}"'), "toml")
    body += "\nEcosystem and target-version gates still apply. Planned rules are listed, but cannot run until ported.\n"
    if command == "analyse":
        presets = data["meta"]["presets"]["analyse"]
        bands = [(0, 1), (2, 3), (4, 5), (6, 8), (9, 10)]
        low, high = bands[presets.index(name)]
        body += f"\nThis preset covers PHPStan levels {low}–{high} and includes every lower preset (levels 0–{high}). "
        body += "Extension rules are included by their mapping preset, not by a PHPStan core level.\n\n"
        switches = [s for p in presets[:presets.index(name) + 1] for s in data["meta"]["preset_switches"].get(p, [])]
        if switches:
            body += "Type switches applied:\n\n" + code("[analyse]\n" + "\n".join(f"{s} = true" for s in switches), "toml")
        body += "\n### What each PHPStan level adds\n\n"
        for level in range(high + 1):
            added = sorted({r["pun"] for r in data["upstream"]["phpstan-classes"].values()
                            if str(r.get("level")) == str(level) and r.get("pun", "").startswith("analyse/")})
            body += f"\n#### Level {level}\n\n"
            body += "\n".join(f"- {rule_link(r)}" for r in added) or {
                7: "Checks each member of a union (`union-types = true`).",
                8: "Checks nullable values (`nullables = true`).",
                9: "Checks explicit mixed (`explicit-mixed = true`).",
                10: "Checks implicit mixed (`implicit-mixed = true`).",
            }.get(level, "No additional mapped rule classes.")
            body += "\n"
    body += f"\n## Enabled rules ({len(on)})\n\n| Rule | Configuration applied | Status |\n| --- | --- | --- |\n"
    for rid, config in sorted(on.items()):
        rule = data["rules"][command][rid.split("/", 1)[1]]
        status = "Ported" if rule.get("ported") else "Planned"
        body += f"| {rule_link(rid)} | `{toml_value(config)}` | {status} |\n"
    if not on:
        body += "\nNo rules.\n"
    off = [f"{command}/{key}" for key in sorted(data["rules"][command]) if f"{command}/{key}" not in on]
    body += f"\n## Rules left off ({len(off)})\n\n"
    body += "\n".join(f"- {rule_link(r)}" for r in off) or "None."
    return page(title, body)


def generate(data: dict) -> dict[Path, str]:
    out = {}
    urls = source_urls()
    defaults = json.loads((ROOT / "crates/pun-config/tests/fixer_options.json").read_text())
    sources = defaultdict(list)
    for source in upstream_rows(data):
        for rid in [source.get("pun"), *source.get("also", [])]:
            if rid:
                sources[rid].append(source)
    out[CONTENT / "rules/meta.ts"] = meta("Rules", [*COMMANDS, "presets", "sets"])
    for command in COMMANDS:
        groups = {}
        for key, rule in sorted(data["rules"][command].items()):
            group, name = key.split("/")
            groups.setdefault(group, []).append(name)
            rid = f"{command}/{key}"
            out[CONTENT / f"rules/{command}/{key}.mdx"] = rule_page(data, rid, rule, sources[rid], urls, defaults)
        out[CONTENT / f"rules/{command}/meta.ts"] = meta(command, list(groups))
        for group, names in groups.items():
            out[CONTENT / f"rules/{command}/{group}/meta.ts"] = meta(group, names)
            counts = ", ".join(f"{cmd}: {sum(key.startswith(group + '/') for key in rules)}"
                               for cmd, rules in data["rules"].items())
            body = prose(data["meta"]["groups"][group]) + f".\n\nAcross commands: {counts}.\n\n<CardGroup cols={{2}}>\n"
            for name in names:
                rid = f"{command}/{group}/{name}"
                rule = data["rules"][command][f"{group}/{name}"]
                body += f'<Card title="{rid}" href="/docs/rules/{rid}">\n\n'
                body += prose(rule.get("summary", "Summary not written yet.")) + "\n\n" + badges(data, rid, rule) + "\n\n</Card>\n"
            out[CONTENT / f"rules/{command}/{group}/index.mdx"] = page(f"{command}/{group}", body + "</CardGroup>")
        links = "\n".join(f"- [{g}](/docs/rules/{command}/{g}) ({len(ns)} rules)" for g, ns in groups.items())
        out[CONTENT / f"rules/{command}/index.mdx"] = page(f"{command} rules", links)
    preset_names = []
    for command in ("format", "analyse"):
        for preset in data["meta"]["presets"][command]:
            slug = f"{command}-{preset}"
            preset_names.append(slug)
            on = format_config(data, preset) if command == "format" else {
                f"analyse/{key}": True for key, rule in data["rules"]["analyse"].items()
                if slug in memberships(data, "analyse", rule)}
            out[CONTENT / f"rules/presets/{slug}.mdx"] = selection_page(data, command, preset, on)
    out[CONTENT / "rules/presets/meta.ts"] = meta("Presets", preset_names)
    out[CONTENT / "rules/presets/index.mdx"] = page("Rule presets", "\n".join(
        f"- [{name}](/docs/rules/presets/{name})" for name in preset_names))
    for name in data["meta"]["sets"]:
        on = {f"lint/{key}": "error" for key, rule in data["rules"]["lint"].items() if name in rule.get("sets", [])}
        out[CONTENT / f"rules/sets/{name}.mdx"] = selection_page(data, "lint", name, on)
    out[CONTENT / "rules/sets/meta.ts"] = meta("Sets", data["meta"]["sets"])
    out[CONTENT / "rules/sets/index.mdx"] = page("Lint sets", "\n".join(
        f"- [{name}](/docs/rules/sets/{name})" for name in data["meta"]["sets"]))
    return out


def sync(output: dict[Path, str], check: bool) -> int:
    # Only files carrying our marker belong to the generator. Never remove handwritten content.
    owned = {p for p in CONTENT.rglob("*")
             if p.suffix in (".mdx", ".ts") and MARKER in p.read_text()}
    stale = sorted(owned - output.keys())
    changed = [p for p, text in output.items() if not p.exists() or p.read_text() != text]
    for path in stale + changed:
        print(f"{'obsolete' if path in stale else 'out of date'}: {path.relative_to(ROOT)}")
    if check:
        return int(bool(stale or changed))
    for path in stale:
        path.unlink()
    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(output[path])
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = tomllib.loads(MAPPING.read_text())
    output = generate(data)
    result = sync(output, args.check)
    print(f"{len(output)} generated files; {'out of date' if result else 'in sync'}")
    return result


if __name__ == "__main__":
    raise SystemExit(main())
