<?php

declare(strict_types=1);

/*
 * The classes and functions PHPStan 2.3.1 loads from its own PHAR without a prefix (PHPStan\, PhpParser\,
 * PHPStan\PhpDocParser\, PHPStan\BetterReflection\), as one stub file with function bodies removed: they exist for
 * every `phpstan analyse` run (extensions and rule tests use them), so Pun scans this stub when an analysed file
 * names one of those namespaces.
 *
 *   php scripts/export-phpstan-api-stub.php > crates/pun-analyse/data/phpstan-api.php
 */

$phar = dirname(__DIR__).'/.oracle/phpstan-phar';
require $phar.'/vendor/autoload.php';

use PhpParser\Node;
use PhpParser\NodeTraverser;
use PhpParser\NodeVisitorAbstract;
use PhpParser\ParserFactory;
use PhpParser\PrettyPrinter\Standard;

$dirs = ['src', 'vendor/nikic/php-parser/lib/PhpParser', 'vendor/phpstan/phpdoc-parser/src', 'vendor/ondrejmirtes/better-reflection/src'];
$parser = (new ParserFactory())->createForHostVersion();
$printer = new Standard();
$strip = new class () extends NodeVisitorAbstract {
    /** @var array<string, string> alias => original, from php-parser's `class_alias()` compatibility calls */
    public array $aliases = [];

    public function leaveNode(Node $node)
    {
        if ($node instanceof Node\Stmt\Expression && $node->expr instanceof Node\Expr\FuncCall
            && $node->expr->name instanceof Node\Name && $node->expr->name->toLowerString() === 'class_alias'
            && count($node->expr->args) === 2) {
            [$original, $alias] = array_map(fn ($a) => $a->value->class->toString(), $node->expr->args);
            $this->aliases[$alias] = $original;
        }
        if ($node instanceof Node\Stmt\ClassMethod && $node->stmts !== null) {
            $node->stmts = [];
        }
        if ($node instanceof Node\Stmt\Function_) {
            $node->stmts = [];
        }
        if ($node instanceof Node\Stmt\Expression || $node instanceof Node\Stmt\If_ || $node instanceof Node\Stmt\Return_) {
            return NodeTraverser::REMOVE_NODE; // top-level code (bootstrap files)
        }

        return null;
    }
};
$traverser = new NodeTraverser();
$traverser->addVisitor($strip);

$files = [];
foreach ($dirs as $dir) {
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($phar.'/'.$dir, FilesystemIterator::SKIP_DOTS));
    foreach ($it as $f) {
        if ($f->getExtension() === 'php') {
            $files[] = $f->getPathname();
        }
    }
}
sort($files);

$all = [];
foreach ($files as $file) {
    $stmts = $traverser->traverse($parser->parse(file_get_contents($file)));
    $hasNamespace = false;
    foreach ($stmts as $s) {
        $hasNamespace = $hasNamespace || $s instanceof Node\Stmt\Namespace_;
    }
    $stmts = array_values(array_filter($stmts, fn ($s) => ! $s instanceof Node\Stmt\Declare_ && ! $s instanceof Node\Stmt\InlineHTML));
    if ($stmts === []) {
        continue;
    }
    if (! $hasNamespace) {
        $stmts = [new Node\Stmt\Namespace_(null, $stmts)];
    }
    array_push($all, ...$stmts);
}
// The aliases, as subclasses (Mago's codex has no class aliases).
ksort($strip->aliases);
foreach ($strip->aliases as $alias => $original) {
    $at = strrpos($alias, '\\');
    $all[] = new Node\Stmt\Namespace_(new Node\Name(substr($alias, 0, $at)), [
        new Node\Stmt\Class_(substr($alias, $at + 1), ['extends' => new Node\Name\FullyQualified($original)]),
    ]);
}
// One print: with a global-namespace block among them, every namespace is printed braced.
echo "<?php\n\n// Generated by scripts/export-phpstan-api-stub.php from PHPStan 2.3.1's PHAR: declarations only.\n";
echo $printer->prettyPrint($all), "\n";
