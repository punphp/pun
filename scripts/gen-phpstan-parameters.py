#!/usr/bin/env python3
"""Writes rules/mapping.toml's [phpstan-parameters]: which PHPStan parameters each analyse rule reads.

    scripts/gen-phpstan-parameters.py      runs scripts/export-phpstan-parameters.php (on .oracle/phpstan) and
                                           replaces the [phpstan-parameters] section of crates/pun-config/rules/mapping.toml

An entry is `rules = [...]`: the Pun rules whose PHPStan classes read the parameter (`pun migrate` writes a changed
value as their option), or `level = true`: a parameter the level sets, which Pun's analyse presets decide. Parameters
that only steer PHPStan's run (cache, tips, feature toggles) are left out; the gated ones are `gated_by` in
[upstream.phpstan-classes].
"""
import json
import pathlib
import re
import subprocess
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
MAPPING = ROOT / "crates/pun-config/rules/mapping.toml"
RUN_ONLY = re.compile(r"^(cache|tips|featureToggles)\.|^deprecationRulesInstalled$")


def kebab(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name.replace(".", "-")).lower()


def main() -> None:
    text = MAPPING.read_text()
    data = tomllib.loads(text)
    classes = data["upstream"]["phpstan-classes"]
    pun = {e["class"]: e["pun"] for e in classes.values() if e.get("pun", "").startswith("analyse/")}
    out = subprocess.run(
        ["php", str(ROOT / "scripts/export-phpstan-parameters.php"), json.dumps(sorted(pun))],
        capture_output=True, text=True, check=True,
    ).stdout
    exported = json.loads(out)
    declared, levels = set(exported["parameters"]), set(exported["levels"])
    rules: dict[str, set[str]] = {}
    for cls, params in exported["rules"].items():
        for p in params:
            if p in declared and p not in levels and not RUN_ONLY.search(p):
                rules.setdefault(p, set()).add(pun[cls])
    lines = [
        "# Which PHPStan parameters the analyse rules read (generated by scripts/gen-phpstan-parameters.py from PHPStan",
        "# 2.3.1, Larastan and strict-rules): `pun migrate` writes a changed value as an option of each rule, named",
        "# kebab-case. `level = true`: the level sets it, so Pun's analyse presets decide it.",
        "[phpstan-parameters]",
    ]
    for p in sorted(rules.keys() | levels):
        key = f'"{p}"' if "." in p else p
        if p in levels:
            lines.append(f"{key} = {{ level = true }}")
        else:
            listed = ", ".join(f'"{r}"' for r in sorted(rules[p]))
            lines.append(f'{key} = {{ option = "{kebab(p)}", rules = [{listed}] }}')
    section = "\n".join(lines) + "\n"
    start = text.find("\n# Which PHPStan parameters the analyse rules read")
    if start == -1:
        text = text.rstrip("\n") + "\n\n" + section
    else:
        end = text.find("\n[", text.index("[phpstan-parameters]", start) + 1)
        text = text[: start + 1] + section + (text[end:] if end != -1 else "")
    MAPPING.write_text(text)


if __name__ == "__main__":
    main()
