/// Level 0 also needs the scope's type of explicit keys and unpacked values.
pub(super) fn typed_expressions(program: &Program) -> Vec<Span> {
    struct Keys(Vec<Span>);
    impl Keys {
        fn key(&mut self, key: &Expression) {
            self.0.push(key.span());
            match key {
                Expression::Parenthesized(p) => self.key(p.expression),
                Expression::UnaryPrefix(u) => self.key(u.operand),
                Expression::Access(Access::ClassConstant(a)) => self.key(a.class),
                _ => {}
            }
        }
    }
    impl<'ast, 'arena> MutWalker<'ast, 'arena, ()> for Keys {
        fn walk_in_key_value_array_element(
            &mut self,
            item: &'ast KeyValueArrayElement<'arena>,
            (): &mut (),
        ) {
            self.key(item.key);
        }
        fn walk_in_variadic_array_element(
            &mut self,
            item: &'ast VariadicArrayElement<'arena>,
            (): &mut (),
        ) {
            self.0.push(item.value.span());
        }
    }
    let mut keys = Keys(Vec::new());
    keys.walk_program(program, &mut ());
    keys.0
}

/// The arrays php-parser has as `List_` (destructuring targets), which are no LiteralArrayNode.
#[derive(Default)]
pub(super) struct State {
    lists: HashSet<Span>,
    /// `None` guards a local copy's source expression currently being resolved.
    constants: Mutex<HashMap<Span, Option<Type>>>,
}

/// `$autoGeneratedIndex`: the biggest integer key so far (null before one, false once a key is unknown).
#[derive(Clone, Copy)]
enum Auto {
    NotYet,
    Known(i64),
    Unknown,
}

/// An array key after `toArrayKey()`.
#[derive(Clone, PartialEq, Eq, Hash)]
enum Key {
    Int(i64),
    Str(Vec<u8>),
}

impl Key {
    /// PHP's key cast of a string: a canonical decimal integer is an int.
    fn of_string(s: &[u8]) -> Key {
        let canonical = std::str::from_utf8(s)
            .ok()
            .and_then(|s| s.parse::<i64>().ok())
            .filter(|i| i.to_string().as_bytes() == s);
        canonical.map_or_else(|| Key::Str(s.to_vec()), Key::Int)
    }

    fn of_float(f: f64) -> Key {
        // ConstantFloatType::toArrayKey(): PHP's zend_dval_to_lval, not Rust's saturating cast. There is
        // no float-to-int helper in php_compat; truncate modulo 2^64 before interpreting the signed word.
        if !f.is_finite() {
            return Key::Int(0);
        }
        let word = 18446744073709551616.0;
        let mut f = f.trunc() % word;
        if f >= -(i64::MIN as f64) {
            f -= word;
        } else if f < i64::MIN as f64 {
            f += word;
        }
        Key::Int(f as i64)
    }

    /// `var_export()`.
    fn export(&self) -> String {
        match self {
            Key::Int(i64::MIN) => "-9223372036854775807-1".into(),
            Key::Int(i) => i.to_string(),
            Key::Str(s) => {
                let s = String::from_utf8_lossy(s);
                format!("'{}'", s.replace('\\', "\\\\").replace('\'', "\\'"))
            }
        }
    }
}

/// A destructuring target (`[...] = `, a `foreach` target): php-parser's `List_` nodes. `short`: a `[...]` here is one
/// (the target's top level, or in a `[...]` list; in `list()` it is an array literal).
pub(super) fn destructuring(c: &mut Checker, target: &Expression, short: bool) {
    let target = unparen(target);
    let (elements, short) = match target {
        Expression::Array(a) if short => (&a.elements, true),
        Expression::List(l) => (&l.elements, false),
        _ => return,
    };
    c.arrays.lists.insert(target.span());
    for element in elements {
        let value = match element {
            ArrayElement::KeyValue(kv) => kv.value,
            ArrayElement::Value(v) => v.value,
            _ => continue,
        };
        destructuring(c, value, short);
    }
}

/// DuplicateKeysInLiteralArraysRule on a `[...]` or `array(...)` literal.
pub(super) fn literal_array<'arena>(
    c: &mut Checker<'_, 'arena>,
    span: Span,
    elements: &TokenSeparatedSequence<'arena, ArrayElement<'arena>>,
) {
    if c.arrays.lists.contains(&span) {
        return;
    }
    let mut duplicate_keys: Vec<Key> = Vec::new();
    let mut printed: HashMap<Key, Vec<String>> = HashMap::new();
    let mut lines: HashMap<Key, Span> = HashMap::new();
    let mut auto = Auto::NotYet;
    let mut seen: Vec<Key> = Vec::new();
    let mut seen_unions: Vec<Vec<Key>> = Vec::new();
    for element in elements {
        let at = element.span();
        let (key, key_types) = match element {
            ArrayElement::KeyValue(kv) => {
                // PHP compares string keys as bytes. Routing literals through Type::ConstString
                // would replace distinct invalid UTF-8 bytes with the same replacement character.
                let values = match unparen(kv.key) {
                    Expression::Literal(Literal::String(s)) => {
                        s.value.map(|value| vec![Key::of_string(value)])
                    }
                    _ => key_type(c, kv.key, c.names, c.class_scope())
                        .as_ref()
                        .and_then(inferred_keys),
                }
                .unwrap_or_default();
                // once the implicit index is unknown an explicit key can't bring it back
                if let [Key::Int(i)] = values.as_slice() {
                    auto = match auto {
                        Auto::NotYet => Auto::Known(*i),
                        Auto::Known(b) => Auto::Known(b.max(*i)),
                        Auto::Unknown => Auto::Unknown,
                    };
                }
                (Some(kv.key), vec![values])
            }
            ArrayElement::Variadic(v) => {
                let next = match auto {
                    Auto::Unknown => continue,
                    Auto::NotYet => Some(0),
                    Auto::Known(i) => i.checked_add(1),
                };
                let keys = c.phpstan_type(v.value).and_then(|t| {
                    declared::with_classes(c, || {
                        unpacked_keys(&t, next, c.php_version >= 80100, c.on(crate::rules::Switches::BLEEDING_EDGE))
                    })
                });
                let Some(mut keys) = keys else {
                    auto = Auto::Unknown;
                    continue;
                };
                for key in &keys {
                    if let Key::Int(i) = key {
                        auto = match auto {
                            Auto::Known(before) => Auto::Known(before.max(*i)),
                            _ => Auto::Known(*i),
                        };
                    }
                }
                // Only a literal spread reports string-key collisions: other expressions have
                // array_merge-style string overrides. Integer keys still consume implicit indices.
                if !matches!(
                    unparen(v.value),
                    Expression::Array(_) | Expression::LegacyArray(_)
                ) {
                    keys.retain(|key| !matches!(key, Key::Str(_)));
                }
                (None, keys.into_iter().map(|key| vec![key]).collect())
            }
            _ => {
                let next = match auto {
                    Auto::Unknown => continue,
                    Auto::NotYet => 0,
                    // PHP throws "Cannot add element to the array as the next element is already occupied"
                    Auto::Known(i64::MAX) => {
                        auto = Auto::Unknown;
                        continue;
                    }
                    Auto::Known(i) => i + 1,
                };
                auto = Auto::Known(next);
                (None, vec![vec![Key::Int(next)]])
            }
        };
        for values in key_types {
            if values.is_empty() {
                auto = Auto::Unknown;
                continue;
            }
            // PHPStan's seenKeys/seenUnions: an overlap alone is not a definite duplicate. A singleton
            // eliminates that possibility from earlier unions, promoting their last remaining possibility.
            let new_values: Vec<_> = values
                .iter()
                .filter(|value| !seen.contains(value))
                .cloned()
                .collect();
            let duplicate = new_values.is_empty();
            if let [new_value] = new_values.as_slice() {
                seen_unions.retain_mut(|union| {
                    if let Some(offset) = union.iter().position(|value| value == new_value) {
                        union.remove(offset);
                        if union.len() == 1 {
                            seen.push(union[0].clone());
                            return false;
                        }
                    }
                    true
                });
                seen.push(new_value.clone());
            } else if !duplicate {
                seen_unions.push(new_values);
            }
            for value in values {
                let print = key.map_or_else(|| value.export(), |key| written(c, key));
                printed.entry(value.clone()).or_default().push(print);
                lines.entry(value.clone()).or_insert(at);
                if duplicate && !duplicate_keys.contains(&value) {
                    duplicate_keys.push(value.clone());
                }
            }
        }
    }
    for value in duplicate_keys {
        let printed = &printed[&value];
        c.report(
            lines[&value],
            "array.duplicateKey",
            format!(
                "Array has {} duplicate keys with value {} ({}).",
                printed.len(),
                value.export(),
                printed.join(", ")
            ),
            None,
        );
    }
}

/// Only the metadata `ArrayUnpackingHelper::getKeyTypes()` reads. Callable arrays have exactly keys 0 and 1.
enum UnpackingArray<'a> {
    Shape(&'a ConstArray),
    Callable,
}

/// `getConstantArrays()`: unions require every member to contribute; intersections collect their shapes.
fn constant_arrays(t: &Type) -> Vec<UnpackingArray<'_>> {
    match t {
        Type::ConstArray(a) => vec![UnpackingArray::Shape(a)],
        Type::Intersection(_) if t.is_callable().yes() && t.is_array().yes() => {
            vec![UnpackingArray::Callable]
        }
        Type::Union(types) | Type::Benevolent(types) => {
            let mut arrays = Vec::new();
            for part in types {
                let inner = constant_arrays(part);
                // BenevolentUnionType::pickFromTypes ignores non-array members, but not arrays
                // whose keys are unknown. Ordinary unions require a shape from every member.
                if inner.is_empty() && (!matches!(t, Type::Benevolent(_)) || part.is_array().yes())
                {
                    return Vec::new();
                }
                arrays.extend(inner);
            }
            arrays
        }
        Type::Intersection(types) => types.iter().flat_map(constant_arrays).collect(),
        Type::Template(t) => constant_arrays(&t.bound),
        _ => Vec::new(),
    }
}

/// PHPStan 2.3.5 `ArrayUnpackingHelper::getKeyTypes()`. Resolve the whole spread before advancing the caller's
/// implicit index: an optional key or an overflow invalidates even keys visited before that failure.
fn unpacked_keys(
    t: &Type,
    mut next: Option<i64>,
    keep_strings: bool,
    bleeding_edge: bool,
) -> Option<Vec<Key>> {
    let arrays = constant_arrays(t);
    if arrays.len() != 1 {
        return (arrays.is_empty()
            && keep_strings
            && t.is_iterable().yes()
            && t.iterable_key_type().is_string().yes())
        .then(Vec::new);
    }
    const CALLABLE_KEYS: [Type; 2] = [Type::ConstInt(0), Type::ConstInt(1)];
    let (keys, optional, sealed) = match &arrays[0] {
        UnpackingArray::Shape(a) => (
            a.keys.as_slice(),
            !a.optional.is_empty(),
            // The model's default builder does not carry BleedingEdgeToggle. Explicit open/closed
            // metadata takes precedence; an ordinary closed shape is sealed only with that toggle.
            (a.unsealed.is_none() && bleeding_edge)
                || matches!(
                    &a.unsealed,
                    Some((
                        Type::Never(NeverKind::Explicit | NeverKind::NonAccepting),
                        _
                    ))
                ),
        ),
        UnpackingArray::Callable => (CALLABLE_KEYS.as_slice(), false, bleeding_edge),
    };
    if !sealed || optional {
        return None;
    }
    let mut keys_out = Vec::new();
    for key in keys {
        // ConstArray's key contract already guarantees a singleton constant string or integer.
        if keep_strings && let Type::ConstString(s) = key {
            keys_out.push(Key::Str(s.clone()));
        } else {
            let index = next?;
            keys_out.push(Key::Int(index));
            next = index.checked_add(1);
        }
    }
    Some(keys_out)
}

/// `toArrayKey()->getConstantScalarValues()`. Reuse the syntax path's PHP scalar-key casts; a union
/// contributes values only when every member does (UnionType::notBenevolentPickFromTypes).
fn inferred_keys(t: &Type) -> Option<Vec<Key>> {
    Some(match t {
        Type::ConstInt(_) | Type::ConstString(_) | Type::ConstBool(_) | Type::Null => {
            vec![of_type(t.clone())]
        }
        Type::ConstFloat(f) => vec![Key::of_float(*f)],
        Type::Bool => vec![Key::Int(0), Key::Int(1)],
        Type::Union(types) | Type::Benevolent(types) => {
            let mut values = Vec::new();
            for t in types {
                for value in inferred_keys(t)? {
                    // toArrayKey() combines equal cast keys before getConstantScalarValues().
                    if !values.contains(&value) {
                        values.push(value);
                    }
                }
            }
            values
        }
        Type::Template(t) => return inferred_keys(&t.bound),
        _ => return None,
    })
}

/// ExprPrinter's output for a key after php-parser's NameResolver: a class name and a qualified constant name print
/// fully qualified.
pub(super) fn written(c: &Checker, e: &Expression) -> String {
    let source = |s: Span| c.written(s);
    let e = unparen(e);
    match e {
        Expression::Literal(Literal::Float(f)) => float_var_export(f.value.0),
        Expression::UnaryPrefix(u)
            if matches!(
                u.operator,
                UnaryPrefixOperator::Negation(_) | UnaryPrefixOperator::Plus(_)
            ) && matches!(unparen(u.operand), Expression::Literal(_)) =>
        {
            format!("{}{}", source(u.operator.span()), written(c, u.operand))
        }
        Expression::Access(Access::ClassConstant(a)) => match a.class {
            Expression::Identifier(id) => {
                format!("\\{}::{}", c.resolved(id), source(a.constant.span()))
            }
            _ => source(e.span()),
        },
        Expression::ConstantAccess(a) => match &a.name {
            Identifier::Local(l) if !c.names.is_imported(&l.span) => source(l.span),
            name => format!("\\{}", c.resolved(name)),
        },
        _ => source(e.span()),
    }
}

/// `$scope->getType($key)`: inference for ordinary expressions, PHPStan's reflection rather than stub placeholder
/// initializers for constants. Keep unions until toArrayKey(), including platform-dependent built-in values.
pub(super) fn key_type(
    c: &Checker,
    key: &Expression,
    names: &ResolvedNames,
    context: Option<&ClassLikeMetadata>,
) -> Option<Type> {
    key_type_with(c, key, names, context, &ExpressionTypes::<RandomState>::Current)
}

/// Resolve optional key/source metadata in one selected scope. The converter must use the same map for
/// the expression's dependencies; missing entries never borrow ordinary inference or its copy cache.
pub(super) fn key_type_from(
    c: &Checker,
    key: &Expression,
    names: &ResolvedNames,
    context: Option<&ClassLikeMetadata>,
    types: &HashMap<Span, TUnion, impl BuildHasher>,
    convert: &dyn Fn(&Expression, &TUnion) -> Type,
) -> Option<Type> {
    key_type_with(c, key, names, context, &ExpressionTypes::Selected { types, convert })
}

enum ExpressionTypes<'a, S> {
    Current,
    Selected {
        types: &'a HashMap<Span, TUnion, S>,
        convert: &'a dyn Fn(&Expression, &TUnion) -> Type,
    },
}

impl<S: BuildHasher> ExpressionTypes<'_, S> {
    fn get(&self, c: &Checker, expression: &Expression) -> Option<Type> {
        match self {
            Self::Current => c.phpstan_type(expression),
            Self::Selected { types, convert } => Some(convert(expression, types.get(&expression.span())?)),
        }
    }

    fn copied(&self, c: &Checker, at: Span) -> Option<Type> {
        match self {
            Self::Current => copied_key(c, at),
            Self::Selected { types, .. } => types.get(&at).map(|raw| c.to_phpstan(raw)),
        }
    }
}

fn key_type_with(
    c: &Checker,
    key: &Expression,
    names: &ResolvedNames,
    context: Option<&ClassLikeMetadata>,
    types: &ExpressionTypes<impl BuildHasher>,
) -> Option<Type> {
    let key = unparen(key);
    Some(match key {
        Expression::Literal(Literal::Integer(i)) => {
            let v = i.value?;
            i64::try_from(v).map_or_else(|_| Type::ConstFloat(v as f64), Type::ConstInt)
        }
        Expression::Literal(Literal::Float(f)) => Type::ConstFloat(f.value.0),
        Expression::Literal(Literal::String(s)) => {
            Type::ConstString(s.value?.to_vec())
        }
        Expression::Literal(Literal::True(_)) => Type::ConstBool(true),
        Expression::Literal(Literal::False(_)) => Type::ConstBool(false),
        Expression::Literal(Literal::Null(_)) => Type::Null,
        Expression::UnaryPrefix(u) => {
            if matches!(
                u.operator,
                UnaryPrefixOperator::Negation(_) | UnaryPrefixOperator::Plus(_)
            ) {
                let value = key_type_with(c, u.operand, names, context, types)?;
                signed(
                    value,
                    matches!(u.operator, UnaryPrefixOperator::Negation(_)),
                )
                .or_else(|| types.get(c, key))?
            } else {
                types.get(c, key)?
            }
        }
        Expression::ConstantAccess(a) => {
            if let Some(value) = types.get(c, key) {
                // An observed local declaration may have a flow-selected value unlike reflection.
                return Some(value);
            }
            let resolved = names.get(&a.name);
            let fallback = match &a.name {
                Identifier::Local(l) if !names.is_imported(&l.span) => Some(l.value),
                _ => None,
            };
            std::iter::once(resolved).chain(fallback).find_map(|n| {
                if let Some(k) = c
                    .codebase
                    .get_constant(n)
                    .filter(|k| !k.flags.is_built_in())
                {
                    // Existence stops namespace fallback even when this constant's value is unknown.
                    Some(k.inferred_type.as_ref().map(|t| c.to_phpstan(t)))
                } else {
                    c.builtins
                        .constants
                        .get(String::from_utf8_lossy(n).as_ref())
                        .map(|s| Some(pun_phpstan::resolve::resolve_str(s, None)))
                }
            })??
        }
        Expression::Access(Access::ClassConstant(a)) => {
            let ClassLikeConstantSelector::Identifier(name) = &a.constant else {
                return None;
            };
            let (holder, late) = match unparen(a.class) {
                Expression::Identifier(id) => (
                    Type::ConstString(names.get(id).to_vec()),
                    false,
                ),
                Expression::Self_(_) => (Type::ConstString(c.display(context?).into_bytes()), false),
                Expression::Parent(_) => (
                    Type::ConstString(declared::parent_name(c.codebase, context?)?.into_bytes()),
                    false,
                ),
                Expression::Static(_) => (Type::Object(c.display(context?), vec![], false), true),
                e => (key_type_with(c, e, names, context, types)?, true),
            };
            receiver_constant(c, &holder, name.value, late, types)?
        }
        Expression::Variable(_) => {
            let actual = types.get(c, key)?;
            // Prelude NAN/INF erase float precision; PHP_DEBUG's 0|1 becomes an integer range. Recover
            // only finite scalar keys from a straight-line copy, never widening the actual narrowed type.
            // A mutation/reference/control-flow join has no source edge.
            if inferred_keys(&actual).is_none()
                && let Some(super::infer::Origin::Copy(from)) = c.origins.get(&key.span())
            {
                types.copied(c, *from)
                    .filter(|source| {
                        inferred_keys(source).is_some() && is_super_type_of(&actual, source).yes()
                    })
                    .unwrap_or(actual)
            } else {
                actual
            }
        }
        _ => types.get(c, key)?,
    })
}

/// Numeric unary +/- before PHP's key cast; negating PHP_INT_MIN produces a float, not an overflowing int.
fn signed(t: Type, negative: bool) -> Option<Type> {
    Some(match t {
        Type::ConstInt(i) if negative => i
            .checked_neg()
            .map_or(Type::ConstFloat(-(i as f64)), Type::ConstInt),
        Type::ConstFloat(f) if negative => Type::ConstFloat(-f),
        Type::ConstInt(_) | Type::ConstFloat(_) => t,
        Type::ConstString(s) => match std::str::from_utf8(&s).ok().and_then(numeric) {
            Some(Value::Int(i)) => signed(Type::ConstInt(i), negative)?,
            Some(Value::Float(f)) => signed(Type::ConstFloat(f), negative)?,
            _ => return None,
        },
        Type::ConstBool(b) => signed(Type::ConstInt(i64::from(b)), negative)?,
        Type::Null => Type::ConstInt(0),
        Type::Union(parts) | Type::Benevolent(parts) => union(
            parts
                .into_iter()
                .map(|p| signed(p, negative))
                .collect::<Option<Vec<_>>>()?,
        ),
        _ => return None,
    })
}

/// ClassConstFetchHandler: a constant class-string is exact, an object/generic class-string is late-bound.
fn receiver_constant(c: &Checker, holder: &Type, name: &[u8], late: bool, types: &ExpressionTypes<impl BuildHasher>) -> Option<Type> {
    match holder {
        Type::NonexistentParent if name.eq_ignore_ascii_case(b"class") => {
            Some(intersect(vec![Type::ClassString(None), Type::Accessory(Accessory::LiteralString)]))
        }
        Type::ConstString(class) => class_constant(c, std::str::from_utf8(class).ok()?, name, false, types),
        Type::Object(class, _, _) | Type::Static(class, _) | Type::This(class) => {
            class_constant(c, class, name, late, types)
        }
        Type::ClassString(Some(bound)) => receiver_constant(c, bound, name, true, types),
        Type::Template(t) => receiver_constant(c, &t.bound, name, late, types),
        Type::Union(parts) | Type::Intersection(parts) => {
            let found: Vec<_> = parts
                .iter()
                .filter_map(|p| receiver_constant(c, p, name, late, types))
                .collect();
            (!found.is_empty()).then(|| union(found))
        }
        _ => None,
    }
}

/// InitializerExprTypeResolver::getClassConstFetchTypeByReflection(): exact fetches use the initializer;
/// late-bound fetches of non-final classes use the reflected PHPDoc/native type, or mixed if overridable.
fn class_constant(c: &Checker, class: &str, name: &[u8], late: bool, types: &ExpressionTypes<impl BuildHasher>) -> Option<Type> {
    let known = reflection::known(c, class);
    if name.eq_ignore_ascii_case(b"class") {
        return (!late || known.is_some_and(|k| k.is_final()))
            .then(|| Type::ConstString(class.into()));
    }
    let known = known?;
    let class = class.trim_start_matches('\\');
    let meta = c.codebase.get_class_like(class.as_bytes());
    let constant = meta.and_then(|k| k.constants.get(&mago_word::word(name)));
    // Built-in stub initializers are frequently placeholders. Read only PHPStan's exported value types,
    // searching inherited interfaces/classes too (DateTime::ATOM lives on DateTimeInterface).
    let ancestors: Vec<_> = match known {
        reflection::Known::User(k) => k
            .all_parent_classes
            .iter()
            .chain(&k.all_parent_interfaces)
            .map(|n| n.to_string())
            .collect(),
        reflection::Known::Builtin(k) => {
            k.ancestors.iter().map(|n| n.to_ascii_lowercase()).collect()
        }
    };
    let builtin = std::iter::once(class.to_ascii_lowercase())
        .chain(ancestors)
        .find_map(|owner| {
            let k = c.builtins.classes.get(&owner)?;
            k.constants
                .iter()
                .find(|(n, _)| n.as_bytes() == name)
                .map(|(_, ty)| pun_phpstan::resolve::resolve_str(ty, Some(&k.name)))
        });
    if constant.is_none() && builtin.is_none() {
        return None;
    }
    if late && !known.is_final() {
        if let Some(ty) = constant.and_then(|k| k.type_metadata.as_ref()) {
            return Some(c.to_phpstan(&ty.type_union));
        }
        if !constant.is_some_and(|k| k.flags.is_final()) {
            return Some(pun_phpstan::types::mixed());
        }
    }
    if let Some(k) = constant.filter(|k| !k.flags.is_built_in()) {
        // Canonical class values are scoped to the implementing owner, not to the trait source span.
        // In particular two unrelated consumers must never share the span-only fallback cache below.
        let value = c.to_phpstan(k.inferred_type.as_ref()?);
        let owner =
            crate::codebase::initializer_owner(c.codebase, meta?.name, mago_word::word(name))
                .and_then(|owner| c.codebase.get_class_like_by_name(owner))?;
        return Some(initializer_order_with(c, k.span, owner, value, types));
    }
    builtin
}

/// The inference union owns values; source initializers own PHPStan's observable array order.
/// Restore only ordering, never a runtime-selected conditional branch or newly evaluated values.
pub(super) fn initializer_order(
    c: &Checker,
    at: Span,
    class: &ClassLikeMetadata,
    value: Type,
) -> Type {
    initializer_order_with(c, at, class, value, &ExpressionTypes::<RandomState>::Current)
}

fn initializer_order_with(
    c: &Checker,
    at: Span,
    class: &ClassLikeMetadata,
    value: Type,
    types: &ExpressionTypes<impl BuildHasher>,
) -> Type {
    // Scaffolds are canonical initializer values, not ordinary expression-flow observations. In
    // particular source_initializer accepts an expression span and retains both ternary branches.
    fn source(
        c: &Checker,
        file: &mago_database::file::File,
        expression: &Expression,
        names: &ResolvedNames,
        class: &ClassLikeMetadata,
        types: &ExpressionTypes<impl BuildHasher>,
    ) -> Type {
        let value = crate::codebase::source_initializer(
            c.codebase,
            file,
            expression.span(),
            class.name,
            c.php_version,
            c.include_settings.path_constants,
            c.files.get(&class.span.file_id).cloned(),
        )
        .expect("initializer expression exists in its source");
        let value = c.to_phpstan(&value);
        ordered(c, file, expression, names, class, &value, types).unwrap_or(value)
    }

    // Match within this initializer's own alternatives, then permute the inferred slots. Neither
    // scaffolds' values nor their optionality may replace the inference-owned result.
    fn restore(value: &Type, source: &Type) -> Type {
        if let Type::Union(parts) = value {
            return Type::Union(parts.iter().map(|part| restore(part, source)).collect());
        }
        if let Type::Union(parts) = source {
            return parts
                .iter()
                .find(|part| is_super_type_of(part, value).yes())
                .map_or_else(|| value.clone(), |part| restore(value, part));
        }
        let (actual, source) = match (value, source) {
            (Type::ConstArray(actual), Type::ConstArray(source))
                if actual.keys.len() == source.keys.len()
                    && source.keys.iter().all(|key| actual.keys.contains(key)) =>
            {
                (actual, source)
            }
            _ => return value.clone(),
        };
        let order: Vec<_> = source
            .keys
            .iter()
            .map(|key| {
                actual
                    .keys
                    .iter()
                    .position(|old| old == key)
                    .expect("matching initializer key")
            })
            .collect();
        let mut result = actual.as_ref().clone();
        result.keys = order.iter().map(|old| actual.keys[*old].clone()).collect();
        result.values = order
            .iter()
            .enumerate()
            .map(|(i, old)| restore(&actual.values[*old], &source.values[i]))
            .collect();
        result.optional = order
            .iter()
            .enumerate()
            .filter_map(|(i, old)| actual.optional.contains(old).then_some(i))
            .collect();
        if !result
            .keys
            .iter()
            .enumerate()
            .all(|(i, key)| key == &Type::ConstInt(i as i64))
        {
            result.is_list = pun_phpstan::types::Tri::No;
        }
        Type::ConstArray(Box::new(result))
    }

    fn ordered(
        c: &Checker,
        file: &mago_database::file::File,
        expression: &Expression,
        names: &ResolvedNames,
        class: &ClassLikeMetadata,
        value: &Type,
        types: &ExpressionTypes<impl BuildHasher>,
    ) -> Option<Type> {
        match expression.unparenthesized() {
            Expression::Conditional(conditional) => {
                let then = source(
                    c,
                    file,
                    conditional.then.unwrap_or(conditional.condition),
                    names,
                    class,
                    types,
                );
                let otherwise = source(c, file, conditional.r#else, names, class, types);
                // InitializerExprTypeResolver::getType(Ternary) unions both arms, independently
                // of the condition. Falsey removal already belongs to the inferred value: this
                // broader scaffold only supplies surviving arrays' source-owned order.
                return Some(restore(value, &union(vec![then, otherwise])));
            }
            Expression::Binary(Binary {
                operator: BinaryOperator::Addition(_),
                lhs,
                rhs,
            }) => {
                let left = source(c, file, lhs, names, class, types);
                let right = source(c, file, rhs, names, class, types);
                let (left, right) = match (&left, &right) {
                    (Type::ConstArray(left), Type::ConstArray(right))
                        if left.unsealed.is_none() && right.unsealed.is_none() =>
                    {
                        (left, right)
                    }
                    _ => return None,
                };
                // InitializerExprTypeResolver::getPlusType starts from the right array, then
                // overwrites duplicate values with the left without moving their existing slots.
                let mut builder = pun_phpstan::types::ShapeBuilder::new();
                for array in [right, left] {
                    for (i, key) in array.keys.iter().enumerate() {
                        builder.set(
                            Some(key.clone()),
                            array.values[i].clone(),
                            array.optional.contains(&i),
                        );
                    }
                }
                return Some(restore(value, &builder.get()));
            }
            _ => {}
        }
        if let Type::Union(parts) = value {
            return Some(Type::Union(
                parts
                    .iter()
                    .map(|part| {
                        ordered(c, file, expression, names, class, part, types)
                            .unwrap_or_else(|| part.clone())
                    })
                    .collect(),
            ));
        }
        let Type::ConstArray(actual) = value else {
            return Some(value.clone());
        };
        let elements = match expression.unparenthesized() {
            Expression::Array(a) => &a.elements,
            Expression::LegacyArray(a) => &a.elements,
            Expression::Access(Access::ClassConstant(_)) => {
                return key_type_with(c, expression, names, Some(class), types)
                    .map(|source| restore(value, &source));
            }
            Expression::ConstantAccess(access) => {
                let constant = c.codebase.get_constant(names.get(access)).or_else(|| {
                    (!access.name.value().contains(&b'\\') && !names.is_imported(&access.name))
                        .then(|| c.codebase.get_constant(access.name.value()))
                        .flatten()
                })?;
                return Some(initializer_order_with(c, constant.span, class, value.clone(), types));
            }
            _ => return None,
        };
        let mut order = Vec::new();
        let mut expressions = Vec::new();
        for element in elements {
            let ArrayElement::KeyValue(kv) = element else {
                // Lists already retain their index order; mixed and spread literals keep the inferred
                // fallback rather than inventing a source order for an unsupported key sequence.
                return None;
            };
            let keys = inferred_keys(&key_type_with(c, kv.key, names, Some(class), types)?)?;
            let key = keys.first().filter(|_| keys.len() == 1)?;
            let key = match key {
                Key::Int(i) => Type::ConstInt(*i),
                Key::Str(s) => Type::ConstString(s.clone()),
            };
            let old = actual.keys.iter().position(|k| k == &key)?;
            if let Some(slot) = order.iter().position(|i| *i == old) {
                expressions[slot] = kv.value;
            } else {
                order.push(old);
                expressions.push(kv.value);
            }
        }
        let mut result = actual.as_ref().clone();
        result.keys = order.iter().map(|i| actual.keys[*i].clone()).collect();
        result.values = order
            .iter()
            .zip(expressions)
            .map(|(old, expression)| {
                ordered(c, file, expression, names, class, &actual.values[*old], types)
                    .unwrap_or_else(|| actual.values[*old].clone())
            })
            .collect();
        result.optional = order
            .iter()
            .enumerate()
            .filter_map(|(i, old)| actual.optional.contains(old).then_some(i))
            .collect();
        if !result
            .keys
            .iter()
            .enumerate()
            .all(|(i, key)| key == &Type::ConstInt(i as i64))
        {
            result.is_list = pun_phpstan::types::Tri::No;
        }
        Some(Type::ConstArray(Box::new(result)))
    }
    match &value {
        Type::ConstArray(_) => {}
        Type::Union(parts) if parts.iter().any(|part| matches!(part, Type::ConstArray(_))) => {}
        _ => return value,
    }
    struct Find<'ast, 'arena> {
        at: Span,
        expression: Option<&'ast Expression<'arena>>,
    }
    impl<'ast, 'arena> MutWalker<'ast, 'arena, ()> for Find<'ast, 'arena> {
        fn walk_in_constant_item(&mut self, item: &'ast ConstantItem<'arena>, (): &mut ()) {
            if item.span() == self.at {
                self.expression = Some(item.value);
            }
        }
        fn walk_in_function_call(&mut self, call: &'ast FunctionCall<'arena>, (): &mut ()) {
            if call.span() == self.at {
                self.expression = call.argument_list.arguments.get(1).map(|arg| arg.value());
            }
        }
        fn walk_in_class_like_constant_item(
            &mut self,
            item: &'ast ClassLikeConstantItem<'arena>,
            (): &mut (),
        ) {
            if item.span() == self.at {
                self.expression = Some(item.value);
            }
        }
    }
    c.file_contents(at.file_id)
        .and_then(|contents| {
            let mut file = mago_database::file::File::ephemeral(
                b"initializer-order.php".as_slice().into(),
                contents.to_vec().into(),
            );
            file.id = at.file_id;
            file.path = c.files.get(&at.file_id).cloned();
            let arena = LocalArena::new();
            let (program, names) = crate::codebase::parse(&arena, &file);
            let mut find = Find {
                at,
                expression: None,
            };
            find.walk_program(program, &mut ());
            find.expression
                .and_then(|e| ordered(c, &file, e, &names, class, &value, types))
        })
        .unwrap_or(value)
}

/// Recover finite keys from an unchanged local copy's source expression. Constant declarations already
/// have canonical metadata; only these ordinary flow expressions may use runtime expression inference.
fn copied_key(c: &Checker, at: Span) -> Option<Type> {
    if let Some(found) = c.arrays.constants.lock().expect("array constants").get(&at) {
        return found.clone();
    }
    c.arrays
        .constants
        .lock()
        .expect("array constants")
        .insert(at, None);
    struct Find<'ast, 'arena> {
        at: Span,
        value: Option<&'ast Expression<'arena>>,
    }
    impl<'ast, 'arena> MutWalker<'ast, 'arena, ()> for Find<'ast, 'arena> {
        fn walk_in_expression(&mut self, e: &'ast Expression<'arena>, (): &mut ()) {
            if e.span() == self.at {
                self.value = Some(e);
            }
        }
    }
    let contents = c.file_contents(at.file_id)?;
    let mut file = mago_database::file::File::ephemeral(
        "array-constant.php".as_bytes().into(),
        contents.to_vec().into(),
    );
    file.id = at.file_id;
    let arena = LocalArena::new();
    let (program, names) = crate::codebase::parse(&arena, &file);
    let mut find = Find { at, value: None };
    find.walk_program(program, &mut ());
    let context = c
        .codebase
        .class_likes
        .values()
        .filter(|k| {
            k.span.file_id == at.file_id
                && k.span.start.offset <= at.start.offset
                && at.end.offset <= k.span.end.offset
        })
        .min_by_key(|k| k.span.end.offset - k.span.start.offset);
    let expression = find.value?;
    let value = key_type(c, expression, &names, context.map(Box::as_ref));
    let value = super::infer::analyse(
        &arena,
        &file,
        program,
        &names,
        c.codebase,
        c.php_version,
        c.on(crate::rules::Switches::POLLUTE_SCOPE_WITH_LOOP_INITIAL_ASSIGNMENTS),
        c.on(crate::rules::Switches::POLLUTE_SCOPE_WITH_ALWAYS_ITERABLE_FOREACH),
        c.on(crate::rules::Switches::POLLUTE_SCOPE_WITH_BLOCK),
        vec![expression.span()],
        Vec::new(),
        &c.file_facts(at.file_id)?.comments,
        c.function_likes.get(&at.file_id).map_or(&[][..], Vec::as_slice),
    )
    .0
    .get(&expression.span())
    .map(|t| c.to_phpstan(t))
    .or(value);
    c.arrays
        .constants
        .lock()
        .expect("array constants")
        .insert(at, value.clone());
    value
}

/// The key of a constant scalar type ([`super::enums::constant_value()`] gives an int, a string, a bool or null).
fn of_type(t: Type) -> Key {
    match t {
        Type::ConstInt(i) => Key::Int(i),
        Type::ConstString(s) => Key::of_string(&s),
        Type::ConstBool(b) => Key::Int(i64::from(b)),
        _ => Key::Str(Vec::new()),
    }
}
