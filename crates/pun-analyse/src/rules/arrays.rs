//! DuplicateKeysInLiteralArraysRule: constant scalar keys, including inferred expressions and finite unions.

use std::collections::{HashMap, HashSet};

use mago_span::{HasSpan, Span};
use mago_syntax::cst::*;
use mago_syntax::walker::MutWalker;
use pun_phpstan::types::Type;

use super::Checker;

/// Level 0 also needs the scope's type of explicit array keys, not just syntax-known constants.
pub(super) fn typed_expressions(program: &Program) -> Vec<Span> {
    struct Keys(Vec<Span>);
    impl<'ast, 'arena> MutWalker<'ast, 'arena, ()> for Keys {
        fn walk_in_key_value_array_element(
            &mut self,
            item: &'ast KeyValueArrayElement<'arena>,
            _: &mut (),
        ) {
            self.0.push(item.key.span());
        }
    }
    let mut keys = Keys(Vec::new());
    keys.walk_program(program, &mut ());
    keys.0
}

/// The arrays php-parser has as `List_` (destructuring targets), which are no LiteralArrayNode.
#[derive(Default)]
pub struct State {
    lists: HashSet<Span>,
}

/// `$autoGeneratedIndex`: the biggest integer key so far (null before one, false once a key is unknown).
#[derive(Clone, Copy)]
enum Auto {
    NotYet,
    Known(i64),
    Unknown,
}

/// An array key after `toArrayKey()`.
#[derive(Clone, PartialEq, Eq, Hash)]
enum Key {
    Int(i64),
    Str(Vec<u8>),
}

impl Key {
    /// PHP's key cast of a string: a canonical decimal integer is an int.
    fn of_string(s: &[u8]) -> Key {
        let canonical = std::str::from_utf8(s)
            .ok()
            .and_then(|s| s.parse::<i64>().ok())
            .filter(|i| i.to_string().as_bytes() == s);
        canonical.map_or_else(|| Key::Str(s.to_vec()), Key::Int)
    }

    fn of_float(f: f64) -> Option<Key> {
        // ponytail: non-finite and wrapping float-to-int casts are not ported. Rust's saturating
        // cast is not PHP's wrapping cast outside this range, so do not invent a constant key.
        (f >= i64::MIN as f64 && f < -(i64::MIN as f64)).then(|| Key::Int(f.trunc() as i64))
    }

    /// `var_export()`.
    fn export(&self) -> String {
        match self {
            Key::Int(i) => i.to_string(),
            Key::Str(s) => {
                let s = String::from_utf8_lossy(s);
                format!("'{}'", s.replace('\\', "\\\\").replace('\'', "\\'"))
            }
        }
    }
}

fn unparenthesized<'e, 'arena>(mut e: &'e Expression<'arena>) -> &'e Expression<'arena> {
    while let Expression::Parenthesized(p) = e {
        e = p.expression;
    }
    e
}

/// A destructuring target (`[...] = `, a `foreach` target): php-parser's `List_` nodes. `short`: a `[...]` here is one
/// (the target's top level, or in a `[...]` list; in `list()` it is an array literal).
pub fn destructuring(c: &mut Checker, target: &Expression, short: bool) {
    let target = unparenthesized(target);
    let (elements, short) = match target {
        Expression::Array(a) if short => (&a.elements, true),
        Expression::List(l) => (&l.elements, false),
        _ => return,
    };
    c.arrays.lists.insert(target.span());
    for element in elements.iter() {
        let value = match element {
            ArrayElement::KeyValue(kv) => kv.value,
            ArrayElement::Value(v) => v.value,
            _ => continue,
        };
        destructuring(c, value, short);
    }
}

/// DuplicateKeysInLiteralArraysRule on a `[...]` or `array(...)` literal.
pub fn literal_array<'arena>(
    c: &mut Checker<'_, 'arena>,
    span: Span,
    elements: &TokenSeparatedSequence<'arena, ArrayElement<'arena>>,
) {
    if c.arrays.lists.contains(&span) {
        return;
    }
    let mut duplicate_keys: Vec<Key> = Vec::new();
    let mut printed: HashMap<Key, Vec<String>> = HashMap::new();
    let mut lines: HashMap<Key, Span> = HashMap::new();
    let mut auto = Auto::NotYet;
    let mut seen: Vec<Key> = Vec::new();
    let mut seen_unions: Vec<Vec<Key>> = Vec::new();
    for element in elements.iter() {
        // assistant's call: a missing element (`[1, , 2]`, a php-parser error outside a list) counts as one without a key
        let (key, at) = match element {
            ArrayElement::KeyValue(kv) => (Some(kv.key), kv.span()),
            // ArrayUnpackingHelper::getKeyTypes() gives no keys for a constant array that is not sealed, which a
            // literal is not without bleeding edge, so (as the oracle shows) an unpacked item's keys are unknown
            ArrayElement::Variadic(_) => {
                auto = Auto::Unknown;
                continue;
            }
            e => (None, e.span()),
        };
        let (values, print) = match key {
            None => {
                let next = match auto {
                    Auto::Unknown => continue,
                    Auto::NotYet => 0,
                    // PHP throws "Cannot add element to the array as the next element is already occupied"
                    Auto::Known(i64::MAX) => {
                        auto = Auto::Unknown;
                        continue;
                    }
                    Auto::Known(b) => b + 1,
                };
                auto = Auto::Known(next);
                (vec![Key::Int(next)], next.to_string())
            }
            Some(key) => {
                let values = key_value(c, key)
                    .map(|value| vec![value])
                    .or_else(|| match unparenthesized(key) {
                        // Keep the existing constant resolver's boundary: Mago's built-in stubs can
                        // contain placeholder values, and late-static constants may be overridden.
                        Expression::ConstantAccess(_)
                        | Expression::Access(Access::ClassConstant(_)) => None,
                        _ => inferred_keys(&c.phpstan_type(key)?),
                    })
                    .unwrap_or_default();
                // once the implicit index is unknown an explicit key can't bring it back
                if let [Key::Int(i)] = values.as_slice() {
                    auto = match auto {
                        Auto::NotYet => Auto::Known(*i),
                        Auto::Known(b) => Auto::Known(b.max(*i)),
                        Auto::Unknown => Auto::Unknown,
                    };
                }
                (values, written(c, key))
            }
        };
        if values.is_empty() {
            auto = Auto::Unknown;
            continue;
        }
        // PHPStan's seenKeys/seenUnions: an overlap alone is not a definite duplicate. A singleton
        // eliminates that possibility from earlier unions, promoting their last remaining possibility.
        let new_values: Vec<_> = values
            .iter()
            .filter(|value| !seen.contains(value))
            .cloned()
            .collect();
        let duplicate = new_values.is_empty();
        if let [new_value] = new_values.as_slice() {
            seen_unions.retain_mut(|union| {
                if let Some(offset) = union.iter().position(|value| value == new_value) {
                    union.remove(offset);
                    if union.len() == 1 {
                        seen.push(union[0].clone());
                        return false;
                    }
                }
                true
            });
            seen.push(new_value.clone());
        } else if !duplicate {
            seen_unions.push(new_values);
        }
        for value in values {
            printed
                .entry(value.clone())
                .or_default()
                .push(print.clone());
            lines.entry(value.clone()).or_insert(at);
            if duplicate && !duplicate_keys.contains(&value) {
                duplicate_keys.push(value.clone());
            }
        }
    }
    for value in duplicate_keys {
        let printed = &printed[&value];
        c.report(
            lines[&value],
            "array.duplicateKey",
            format!(
                "Array has {} duplicate keys with value {} ({}).",
                printed.len(),
                value.export(),
                printed.join(", ")
            ),
            None,
        );
    }
}

/// `toArrayKey()->getConstantScalarValues()`. Reuse the syntax path's PHP scalar-key casts; a union
/// contributes values only when every member does (UnionType::notBenevolentPickFromTypes).
fn inferred_keys(t: &Type) -> Option<Vec<Key>> {
    Some(match t {
        Type::ConstInt(_) | Type::ConstString(_) | Type::ConstBool(_) | Type::Null => {
            vec![of_type(t.clone())]
        }
        Type::ConstFloat(f) => vec![Key::of_float(*f)?],
        Type::Bool => vec![Key::Int(0), Key::Int(1)],
        Type::Union(types) | Type::Benevolent(types) => {
            let mut values = Vec::new();
            for t in types {
                for value in inferred_keys(t)? {
                    // toArrayKey() combines equal cast keys before getConstantScalarValues().
                    if !values.contains(&value) {
                        values.push(value);
                    }
                }
            }
            values
        }
        Type::Template(t) => return inferred_keys(&t.bound),
        _ => return None,
    })
}

/// ExprPrinter's output for a key after php-parser's NameResolver: a class name and a qualified constant name print
/// fully qualified.
// assistant's call: php-parser's printer reprints a literal in its written form, so the source text stands in for it
fn written(c: &Checker, e: &Expression) -> String {
    let source =
        |s: Span| String::from_utf8_lossy(&c.file.contents[s.to_range_usize()]).into_owned();
    let e = unparenthesized(e);
    match e {
        Expression::Access(Access::ClassConstant(a)) => match a.class {
            Expression::Identifier(id) => {
                format!("\\{}::{}", c.resolved(id), source(a.constant.span()))
            }
            _ => source(e.span()),
        },
        Expression::ConstantAccess(a) => match &a.name {
            Identifier::Local(l) if !c.names.is_imported(&l.span) => source(l.span),
            name => format!("\\{}", c.resolved(name)),
        },
        _ => source(e.span()),
    }
}

/// The one value of `$scope->getType($key)->toArrayKey()->getConstantScalarValues()`, `None` when the key's type is
/// not known here.
fn key_value(c: &Checker, key: &Expression) -> Option<Key> {
    let key = unparenthesized(key);
    let value = match key {
        Expression::Literal(Literal::Integer(i)) => Key::Int(i64::try_from(i.value?).ok()?),
        Expression::Literal(Literal::Float(f)) => Key::of_float(f.value.0)?,
        Expression::Literal(Literal::String(s)) => Key::of_string(s.value?),
        Expression::Literal(Literal::True(_)) => Key::Int(1),
        Expression::Literal(Literal::False(_)) => Key::Int(0),
        Expression::Literal(Literal::Null(_)) => Key::Str(Vec::new()),
        Expression::UnaryPrefix(u) => {
            let negate = match u.operator {
                UnaryPrefixOperator::Negation(_) => true,
                UnaryPrefixOperator::Plus(_) => false,
                _ => return None,
            };
            match unparenthesized(u.operand) {
                Expression::Literal(Literal::Integer(i)) => {
                    let i = i64::try_from(i.value?).ok()?;
                    Key::Int(if negate { -i } else { i })
                }
                Expression::Literal(Literal::Float(f)) => {
                    Key::of_float(if negate { -f.value.0 } else { f.value.0 })?
                }
                _ => return None,
            }
        }
        Expression::ConstantAccess(a) => {
            let resolved = c.names.get(&a.name.span());
            let fallback = match &a.name {
                Identifier::Local(l) if !c.names.is_imported(&l.span) => Some(l.value),
                _ => None,
            };
            let constant = std::iter::once(resolved)
                .chain(fallback)
                .find_map(|n| c.codebase.get_constant(n))
                .filter(|k| !k.flags.is_built_in())?;
            let [atomic] =
                <&[_; 1]>::try_from(constant.inferred_type.as_ref()?.types.as_ref()).ok()?;
            of_type(super::enums::constant_value(c, atomic)?)
        }
        Expression::Access(Access::ClassConstant(a)) => {
            let class = match a.class {
                Expression::Identifier(id) => c.resolved(id),
                Expression::Self_(_) => c.display(c.class_scope()?),
                Expression::Parent(_) => {
                    let parent = c.class_scope()?.direct_parent_class?;
                    String::from_utf8_lossy(
                        c.class_like(&String::from_utf8_lossy(parent.as_bytes()))
                            .found()?
                            .original_name
                            .as_bytes(),
                    )
                    .into_owned()
                }
                // ponytail: `static::X` is the constant's value only when it cannot be overridden
                _ => return None,
            };
            let ClassLikeConstantSelector::Identifier(name) = &a.constant else {
                return None;
            };
            if name.value.eq_ignore_ascii_case(b"class") {
                Key::of_string(class.as_bytes())
            } else {
                let k = c.class_like(&class).found()?;
                // ponytail: built-in classes' constants (PHP's values per version) are not ported
                if k.flags.is_built_in() {
                    return None;
                }
                let constant = k.constants.get(&mago_word::word(name.value))?;
                of_type(super::enums::constant_value(
                    c,
                    constant.inferred_type.as_ref()?,
                )?)
            }
        }
        _ => return None,
    };
    Some(value)
}

/// The key of a constant scalar type ([`super::enums::constant_value()`] gives an int, a string, a bool or null).
fn of_type(t: Type) -> Key {
    match t {
        Type::ConstInt(i) => Key::Int(i),
        Type::ConstString(s) => Key::of_string(s.as_bytes()),
        Type::ConstBool(b) => Key::Int(i64::from(b)),
        _ => Key::Str(Vec::new()),
    }
}
